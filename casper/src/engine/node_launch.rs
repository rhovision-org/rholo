/// **The ceremony identity the inputs force** (issue #456, Law 84): the bonds file's first bond.
///
/// The local validator's key is used when it *is* that bond. The autogenerated-bonds path writes a
/// `<public_key>.sk` beside the bonds file for every generated validator, so the first bond's key is
/// available there; a network node, which has neither, refuses rather than create a private chain —
/// exactly the failure the retired `rnode-c` lived in for a month.
fn resolve_genesis_ceremony(
    bonds_path: &str,
    local: &ValidatorIdentity,
) -> Result<(PublicKey, ValidatorIdentity), String> {
    let first = bonds_parser::first_bond(Path::new(bonds_path))?;
    if local.public_key == first {
        return Ok((first, local.clone()));
    }
    if let Some(identity) = generated_ceremony_identity(bonds_path, &first) {
        return Ok((first, identity));
    }
    Err(format!(
        "the genesis ceremony must be run by the first bonded validator (issue #456): the bonds \
         file's first entry is {}, this node's key is {}. Refusing to create a local genesis — \
         start with --bootstrap to join the existing chain.",
        base16::encode(first.bytes()),
        base16::encode(local.public_key.bytes())
    ))
}

/// The autogen ceremony key: `<first bond>.sk` beside the bonds file, if it exists and derives that
/// bond's public key.
fn generated_ceremony_identity(bonds_path: &str, first: &PublicKey) -> Option<ValidatorIdentity> {
    let path = Path::new(bonds_path);
    let sk = path
        .parent()?
        .join(format!("{}.sk", base16::encode(first.bytes())));
    let hex = std::fs::read_to_string(sk).ok()?;
    let bytes = base16::decode(hex.trim())?;
    let identity = ValidatorIdentity::from_private_key(PrivateKey::new(bytes)).ok()?;
    (identity.public_key == *first).then_some(identity)
}

pub async fn create_genesis_block(
    validator: &ValidatorIdentity,
    shard_id: &str,
    block_number: i64,
    bonds_path: &str,
    autogen_shard_size: i32,
    vaults_path: &str,
    minimum_bond: i64,
    maximum_bond: i64,
    epoch_length: i32,
    quarantine_length: i32,
    number_of_active_validators: i32,
    executor_share: NonNegI64,
    absence_slack: NonNegI64,
    participation_grace: NonNegI64,
    min_phlo_price: NonNegI64,
    max_number_of_parents: i64,
    pos_multi_sig_public_keys: &[String],
    pos_multi_sig_quorum: i32,
    pos_vault_pub_key: &str,
    system_contract_pub_key: &str,
    dev_tax_address: &str,
    dev_tax_vesting_blocks: i64,
    runtime: &RuntimeManager,
) -> Result<BlockMessage, String> {
    // Initial REV vaults, with the developer allocation derived from their total (Law 78). This is
    // the same derivation `genesis_descriptors_from_config` applies, so the block this ceremony
    // creates and the descriptors every node replays carry the same vaults — and the same genesis
    // post-state hash.
    let vaults = vault_parser::parse(Path::new(vaults_path))?;
    // The developer allocation is *derived* from the parsed vaults and rides into the genesis as a
    // vesting account, exactly where `genesis_descriptors_from_config` derives it, so the block this
    // ceremony creates and the descriptors every node replays carry the same value (Laws 78–79).
    let dev_vesting = crate::genesis::dev_allocation(&vaults, dev_tax_address)?;

    // Initial validators.
    let bonds = bonds_parser::parse_or_generate(Path::new(bonds_path), autogen_shard_size)?;
    // **The inputs force the ceremony's identity** (issue #456, Law 84): the first bond in the file.
    // Its key signs the blessed deploys and fills the block's `sender`, and both enter the block
    // hash, so any other local key would produce a different genesis — a private chain.
    let (first_bond, ceremony) = resolve_genesis_ceremony(bonds_path, validator)?;
    let validators: Vec<Validator> = bonds
        .into_iter()
        .map(|(pk, stake)| Validator { pk, stake })
        .collect();

    // Run the genesis deploys and create the block.
    let genesis = Genesis {
        sender: first_bond,
        shard_id: shard_id.to_string(),
        block_number,
        proof_of_stake: ProofOfStake {
            // The config is where a signed number becomes a protocol parameter, so this is where a
            // negative one is refused rather than carried (deferred item 1d). Not clamped: "no
            // minimum" and "a minimum of -1" are different intentions, and only one of them is
            // expressible here.
            minimum_bond: NonNegI64::try_from(minimum_bond)
                .map_err(|e| format!("casper.genesis.bond-minimum must not be negative: {e}"))?,
            maximum_bond: NonNegI64::try_from(maximum_bond)
                .map_err(|e| format!("casper.genesis.bond-maximum must not be negative: {e}"))?,
            validators,
            epoch_length,
            quarantine_length,
            number_of_active_validators,
            executor_share,
            absence_slack,
            participation_grace,
            min_phlo_price,
            max_number_of_parents,
            pos_multi_sig_public_keys: pos_multi_sig_public_keys.to_vec(),
            pos_multi_sig_quorum,
            pos_vault_pub_key: pos_vault_pub_key.to_string(),
            dev_tax_vesting_blocks: NonNegI64::try_from(dev_tax_vesting_blocks).map_err(|e| {
                format!("casper.genesis.dev-tax-vesting-blocks must not be negative: {e}")
            })?,
        },
        registry: Registry {
            system_contract_pub_key: system_contract_pub_key.to_string(),
        },
        vaults,
        dev_vesting,
    };

    crate::genesis::create_genesis_block(&ceremony, &genesis, runtime).await
}

/// Create one shard's genesis block from its [`ShardSpec`] (port of
/// `NodeLaunch.createGenesisBlockFromConfig`).
pub async fn create_genesis_block_from_config(
    validator: &ValidatorIdentity,
    spec: &ShardSpec,
    runtime: &RuntimeManager,
) -> Result<BlockMessage, String> {
    let gbd = &spec.genesis_block_data;
    // The block's shard id is the spec's validated *full* id (`{parent-shard-id}/{shard-name}`),
    // matching the proposer (`Proposer::apply`), the block receiver's `check_if_of_interest` and
    // both deploy APIs. Passing the bare `shard_name` here made the genesis block carry an id
    // ("root") that no later block or deploy shares ("/root"), so a genesis block received from a
    // peer was dropped by the receiver's equality check.
    let shard_id = spec.shard_id.to_string();
    // The producer's share, refused rather than clamped like the bond bounds: a share over the whole
    // would pay a producer more than the deploy burned, out of the stake the same vault holds for
    // every other validator.
    let executor_share = NonNegI64::try_from(i64::from(gbd.executor_share))
        .map_err(|e| format!("casper.genesis.executor-share must not be negative: {e}"))?;
    if i64::from(executor_share) > 10_000 {
        return Err(format!(
            "casper.genesis.executor-share is {} basis points, above the whole of what a deploy burns",
            i64::from(executor_share)
        ));
    }
    let absence_slack = NonNegI64::try_from(i64::from(gbd.absence_slack))
        .map_err(|e| format!("casper.genesis.absence-slack must not be negative: {e}"))?;
    // The "absent means the binary rule" reading has already been applied where this `gbd` was parsed
    // (`configuration::hocon`), so this is the value and not a second fallback.
    let participation_grace = NonNegI64::try_from(i64::from(gbd.participation_grace))
        .map_err(|e| format!("casper.genesis.participation-grace must not be negative: {e}"))?;
    // The fee floor is committed rather than only configured (see `PosParams::min_phlo_price`), so a
    // negative one is refused here like the other genesis numbers: "no floor" is `0`.
    let min_phlo_price = NonNegI64::try_from(gbd.min_phlo_price)
        .map_err(|e| format!("casper.min-phlo-price must not be negative: {e}"))?;
    create_genesis_block(
        validator,
        &shard_id,
        gbd.genesis_block_number,
        &gbd.bonds_file,
        spec.autogen_shard_size,
        &gbd.wallets_file,
        gbd.bond_minimum,
        gbd.bond_maximum,
        gbd.epoch_length,
        gbd.quarantine_length,
        gbd.number_of_active_validators,
        executor_share,
        absence_slack,
        participation_grace,
        min_phlo_price,
        i64::from(gbd.max_number_of_parents),
        &gbd.pos_multi_sig_public_keys,
        gbd.pos_multi_sig_quorum,
        &gbd.pos_vault_pub_key,
        &gbd.system_contract_pub_key,
        &gbd.dev_tax_address,
        gbd.dev_tax_vesting_blocks,
        runtime,
    )
    .await
}

/// Wait until at least one peer connection is established (port of `waitForFirstConnection`).
async fn wait_for_first_connection(connections: &ConnectionsCell, log: &dyn Log) {
    let source = LogSource::new("casper.engine.NodeLaunch");
    loop {
        if !connections.read().await.is_empty() {
            return;
        }
        log.debug(source, "Waiting for first connection...");
        tokio::time::sleep(Duration::from_millis(250)).await;
    }
}

/// Create, store and broadcast one shard's genesis block (port of
/// `createStoreBroadcastGenesis`).
async fn create_store_broadcast_genesis(
    validator_identity_opt: Option<&ValidatorIdentity>,
    spec: &ShardSpec,
    runtime_manager: &RuntimeManager,
    block_store: &BlockStore,
    approved_store: &ApprovedStore,
    dag: &dyn BlockDagStorage,
    comm_util: &CommUtil,
    log: &dyn Log,
) -> Result<(), String> {
    let source = LogSource::new("casper.engine.NodeLaunch");
    let validator = validator_identity_opt.ok_or_else(|| {
        "To create genesis block node must provide validator private key".to_string()
    })?;

    let genesis_block = create_genesis_block_from_config(validator, spec, runtime_manager).await?;
    log.info(
        source,
        &format!(
            "Sending genesis block {} to peers...",
            genesis_block.block_hash.to_hex()
        ),
    );

    let genesis_fringe = FinalizedFringe {
        hashes: Vec::new(),
        state_hash: genesis_block.pre_state_hash,
        ancestry: Vec::new(),
    };

    put_block(block_store, genesis_block.clone()).await?;
    put_approved_block(approved_store, genesis_fringe.clone()).await?;
    let genesis_post = genesis_block.post_state_hash;
    insert_genesis(dag, genesis_block).await?;
    // **The genesis block is accepted: publish its state** (law 80, B40). Its checkpoint recorded the
    // root as known; without this the pointer would stay at the empty root until the first accepted
    // block.
    if let Err(e) = runtime_manager
        .publish_accepted_root(Blake2b256Hash::from_byte_array(genesis_post.as_bytes()))
        .await
    {
        log.warn(source, &format!("could not publish the genesis root: {e}"));
    }
    comm_util
        .stream_to_peers(&FinalizedFringeSerde.mk_packet(&genesis_fringe), None)
        .await;
    Ok(())
}

/// The node launch mode dispatch (port of `NodeLaunch.apply`).
#[allow(clippy::too_many_arguments)]
pub async fn apply<I: RSpaceImporter + Send + 'static, E: RSpaceExporter>(
    mut packet_rx: mpsc::Receiver<PeerMessage>,
    incoming_blocks: mpsc::Sender<BlockMessage>,
    spec: ShardSpec,
    trim_state: bool,
    // **An operator-named block to sync to instead of a finalised fringe** (C259). See
    // `CasperConf::sync_anchor`; only consulted when this node's DAG is empty.
    sync_anchor: Option<String>,
    expected_genesis_hash: Option<String>,
    // **May this node reset itself?** (F-U5-01's acting half, #320.) Off means the detector still
    // counts, logs and dry-runs the divergence but nothing acts on it — the behaviour of every build
    // before this one. See `CasperConf::self_reset` for why it is an operator switch and not automatic.
    self_reset: bool,
    // Operator switch, threaded to `NodeRunning`: when set, this node refuses store-items
    // (state-sync) requests (port of the Scala's `disableStateExporter`).
    disable_state_exporter: bool,
    validator_identity_opt: Option<ValidatorIdentity>,
    standalone: bool,
    // **Whether the node was started in dev mode.** Consulted only at the genesis-creation branch
    // below, and only to decide whether an unset `dev-tax-address` is a refusal (Law 78). Devnets run
    // in dev mode — `tools/devnet.sh` starts every node it launches with `--dev-mode` — so the gate
    // bites on a production genesis and nowhere else.
    dev_mode: bool,
    transport: Arc<dyn TransportLayer>,
    comm_util: Arc<CommUtil>,
    block_retriever: Arc<BlockRetriever>,
    connections: ConnectionsCell,
    rp_conf: RPConf,
    runtime_manager: Arc<RuntimeManager>,
    block_store: BlockStore,
    approved_store: ApprovedStore,
    dag: Arc<dyn BlockDagStorage>,
    importer: I,
    exporter: E,
    log: Arc<dyn Log>,
) -> Result<(), String> {
    let source = LogSource::new("casper.engine.NodeLaunch");

    // **The operator's anchor, parsed once** (C259): the sync phase names it in its fringe request, and
    // the running phase walks to it. Parsed here rather than in the branch because a `--sync-anchor` typo
    // must be refused whatever this node's DAG looks like — the boot path is not the only reader now.
    let mut boot_anchor = match sync_anchor.as_deref() {
        None => None,
        Some(hex) => Some(
            BlockHash::try_from_hex(hex)
                .map_err(|e| format!("--sync-anchor `{hex}` is not a block hash: {e}"))?,
        ),
    };

    let expected_genesis_hash = expected_genesis_hash
        .as_deref()
        .map(|hash| {
            BlockHash::try_from_hex(hash)
                .map_err(|e| format!("--expected-genesis-hash `{hash}` is invalid: {e}"))
        })
        .transpose()?;
    let repr = dag.get_representation().await;
    let pending_recovery = approved_store
        .get(&[RECOVERY_PENDING_KEY])
        .await?
        .into_iter()
        .next()
        .flatten();
    if repr.dag_set.is_empty() && standalone && pending_recovery.is_none() {
        if expected_genesis_hash.is_some() {
            return Err(
                "a pinned network genesis cannot be created by a standalone node".to_string(),
            );
        }
        // **The last point at which the developer allocation is still decidable** (Law 78). A genesis
        // vault cannot be added afterwards without a hard fork, so an unset address is refused *here*,
        // where the node is about to build genesis and the operator can still act. The condition and
        // its sentence live in `dev_tax`, next to the rule, so a test drives them without a node; what
        // this branch supplies is the context — being reachable only when the DAG is empty is what
        // keeps a standalone node *restarting* onto a chain it built (the public testnet's bootstrap,
        // whose genesis predates this key) from being refused for a decision it already made.
        crate::genesis::dev_tax::refuse_a_production_genesis_without_an_address(
            dev_mode,
            &spec.genesis_block_data.dev_tax_address,
        )?;
        crate::genesis::dev_tax::refuse_a_production_genesis_with_a_zero_vesting_term(
            dev_mode,
            &spec.genesis_block_data.dev_tax_address,
            spec.genesis_block_data.dev_tax_vesting_blocks,
        )?;
        log.info(
            source,
            "Starting as genesis master, creating genesis block...",
        );
        create_store_broadcast_genesis(
            validator_identity_opt.as_ref(),
            &spec,
            runtime_manager.as_ref(),
            &block_store,
            &approved_store,
            dag.as_ref(),
            comm_util.as_ref(),
            log.as_ref(),
        )
        .await?;
    } else if repr.dag_set.is_empty() || pending_recovery.is_some() {
        log.info(source, "Starting from bootstrap node, syncing LFS...");
        let engine = Arc::new(tokio::sync::Mutex::new(
            NodeSyncing::new(
                transport.clone(),
                rp_conf.clone(),
                block_store.clone(),
                dag.clone(),
                approved_store.clone(),
                comm_util.clone(),
                log.clone(),
                validator_identity_opt.clone(),
                trim_state,
                importer,
            )
            .with_replay(RecoveryReplay {
                runtime: runtime_manager.clone(),
                shard_id: spec.shard_id.to_string(),
                min_phlo_price: spec.genesis_block_data.min_phlo_price,
                max_number_of_parents: spec.genesis_block_data.max_number_of_parents,
                expected_genesis: expected_genesis_hash,
                anchor: boot_anchor,
            }),
        ));
        // **A named anchor replaces the fringe request** (C259). A peer with no finalised fringe answers
        // a `FinalizedFringeRequest` with **genesis** (`node_running.rs`), so a wiped joiner syncs to
        // block 0 and can never re-enter sync — which is the state a chain with frozen finality is in,
        // and the reason this switch exists. The anchor is the block the operator's reconciliation
        // computed: the deepest height a strict supermajority of stake agrees on.
        //
        // Nothing else about the sync changes. `request_blocks` walks from whatever hashes it is given
        // (`lfs_block_requester.rs`), so seeding it with an anchor rather than with a peer's fringe is
        // the same machinery with a different root — and `request_tuple_space` then pulls the state at
        // the anchor's post-state, exactly as it would for a fringe.
        let anchor = boot_anchor;
        // **The anchor is named *in the request*, not fetched and patched in afterwards** (C259a).
        // Seeding the sync from the anchor block alone left `ancestry` empty, which bypasses exactly the
        // #139 fix that makes a restored block replayable: no block below the anchor then carries the
        // fringe state the joiner cannot derive, the joiner falls back to deriving it, that derivation
        // needs a sidecar the LFS transfer does not send, and the node stalls **at** the anchor —
        // silently near the tip, and loudly on an older one (`validateBlockCheckpoint failed:
        // regenerated mergeable channels…`). The responder now builds the fringe *and its ancestry* from
        // the named block, so a recovery restore carries the same data the ordinary fringe path does.
        //
        // Nothing else about the sync changes. `request_blocks` walks from whatever hashes it is given
        // (`lfs_block_requester.rs`), so seeding it with an anchor rather than with a peer's fringe is
        // the same machinery with a different root — and `request_tuple_space` then pulls the state at
        // the anchor's post-state, exactly as it would for a fringe.
        if let Some(hash) = anchor {
            if rp_conf.bootstrap.is_none() {
                return Err(
                    "--sync-anchor needs a bootstrap to ask for the anchor's fringe, and this node \
                     has none configured"
                        .to_string(),
                );
            }
            log.info(
                source,
                &format!(
                    "Syncing to the operator-named anchor {} rather than to a fringe a peer offers: \
                     with finality frozen no peer has one, and the answer to an ordinary fringe request \
                     would be the genesis block (C259)",
                    hash.to_hex()
                ),
            );
        }
        // With no anchor this *is* the ordinary request; with one, the same request names the root.
        let received = { engine.lock().await.initial_fringe_received_handle() };
        let request = comm_util.request_initial_fringe(trim_state, anchor, received);
        tokio::pin!(request);

        // Handle packets concurrently with the syncing-finished signal, and with the **terminal**
        // one (AUDIT C181, #125). `finished` is the successful exit — the state was restored, go on
        // to `NodeRunning`. `terminal` is the other one: the sync retries are spent and this node
        // cannot reach the approved state, so it stops serving rather than sitting in `NodeSyncing`
        // for good, which is the state no rule left. Signalling `finished` here instead would move
        // the node into `NodeRunning` on a DAG it never populated, which is what C68 exists to
        // prevent — the two facts are different and get different signals.
        let finished = { engine.lock().await.finished_handle() };
        let terminal = { engine.lock().await.terminal_handle() };
        let handle_loop = async {
            while let Some(pm) = packet_rx.recv().await {
                let mut guard = engine.lock().await;
                if let Err(err) = guard.handle(&pm.peer, &pm.message).await {
                    log.warn(
                        source,
                        &format!("Error handling message from {}: {err}", pm.peer),
                    );
                }
            }
        };
        tokio::pin!(handle_loop);
        let mut awaiting_initial_fringe = true;
        loop {
            tokio::select! {
                _ = &mut handle_loop => break,
                _ = finished.notified() => break,
                result = &mut request, if awaiting_initial_fringe => {
                    result?;
                    awaiting_initial_fringe = false;
                }
                _ = terminal.notified() => {
                // **The reason travels with the sentence** (C271/C268). "The retries are spent" is
                // only half the fact, and without *why* the operator's one error line said the node
                // was giving up and nothing about what it could not restore. The failure is read from
                // the same static the status surface carries, so the log line and `/api/v1/status`
                // agree; the fallback keeps the old wording if the reading is somehow absent rather
                // than printing `None`.
                let reason = crate::engine::node_syncing::sync_state()
                    .and_then(|state| state.last_failure);
                let message = match reason {
                    Some(reason) => format!(
                        "LFS state sync is terminal: the approved state could not be restored and the \
                         retries are spent: {reason}, so this node is stopping rather than serving a \
                         chain it never synced"
                    ),
                    None => "LFS state sync is terminal: the approved state could not be restored and \
                             the retries are spent, so this node is stopping rather than serving a \
                             chain it never synced"
                        .to_string(),
                };
                    return Err(message);
                }
            }
        }
    } else {
        // **A node that reset itself is not simply reconnecting** (F-U5-01's crash window, register
        // C274; law 72). Its DAG was deliberately truncated to an anchor, so running on what it holds
        // would be running on a chain it chose to leave — and if the process died part-way through the
        // reset's durable effects, its block store holds bodies the DAG does not, which the receiver
        // reads as *"stored but not yet validated"* and re-injects above the anchor. `resume_after_reset`
        // re-applies **every** effect the completion record brackets — the two stores and the runtime
        // root — and names the anchor the catch-up walk below must start from. With no marker this is the
        // ordinary reconnection it has always been.
        if let Some(anchor) = crate::engine::reset::resume_after_reset(
            &dag,
            &block_store,
            &runtime_manager,
            &log,
            source,
        )
        .await?
        {
            // **A contradicting pair is refused, not resolved with a warning** (W-N11-01): see
            // [`crate::engine::reset::boot_anchor_after_reset`] for why the record wins and why
            // picking in silence is the defect — on a store the operator did not create, the record
            // is a planted restore point.
            boot_anchor = Some(crate::engine::reset::boot_anchor_after_reset(
                boot_anchor,
                anchor,
            )?);
        } else {
            log.info(source, "Reconnecting to existing network...");
        }
    }

    // **The derived-index audit, at every boot** (B39, HAZOP F-U17-11). It is independent of the reset
    // marker: a store can carry stale rows from a crash on an older build, or from a rewind whose empty
    // metadata drop skipped the cleanup. The repair is idempotent and derives the stale rows from the
    // surviving block set. A failure is logged and the node runs — the rows make the proposer skip a
    // pooled deploy (its replay guard reads the index), which is a defect to repair on the next boot,
    // not a reason to refuse to serve a chain.
    let audit_started = std::time::Instant::now();
    match dag.repair_derived_indexes().await {
        Ok((0, 0)) => {}
        Ok((deploy_rows, deployer_rows)) => log.warn(
            source,
            &format!(
                "boot index audit repaired {deploy_rows} deploy-index and {deployer_rows} \
                 deployer-index row(s) that named a block this DAG does not hold (B39, F-U17-11; {} ms)",
                audit_started.elapsed().as_millis()
            ),
        ),
        Err(e) => log.warn(
            source,
            &format!(
                "boot index audit could not run: {e}; stale derived-index rows may make the proposer \
                 skip a pooled deploy until it succeeds"
            ),
        ),
    }

    // **Republish the latest accepted root** (law 80, B40, HAZOP F-U17-10). A block that was inserted
    // before a crash left its checkpoint's root recorded as *known* and never published; the tip's
    // post-state is an accepted state, so it is a legitimate `CURRENT_ROOT`. A root this store does
    // not know is not published — the pointer is left where it was and the mismatch is logged.
    {
        let repr = dag.get_representation().await;
        if let Some(tip) = repr.latest_fringe().iter().max_by_key(|m| m.height) {
            let tip_hash = tip.id;
            match block_store.get(&[tip_hash]).await {
                Ok(blocks) => match blocks.into_iter().flatten().next() {
                    Some(block) => {
                        let root =
                            Blake2b256Hash::from_byte_array(block.post_state_hash.as_bytes());
                        match runtime_manager.publish_accepted_root(root).await {
                            Ok(true) => log.info(
                                source,
                                &format!(
                                    "republished CURRENT_ROOT at the latest accepted block {}",
                                    tip_hash.to_hex()
                                ),
                            ),
                            Ok(false) => log.warn(
                                source,
                                &format!(
                                    "the latest accepted block {} names a root this store does not \
                                     know; CURRENT_ROOT is left where it was",
                                    tip_hash.to_hex()
                                ),
                            ),
                            Err(e) => log.warn(
                                source,
                                &format!("could not republish CURRENT_ROOT: {e}"),
                            ),
                        }
                    }
                    None => log.warn(
                        source,
                        &format!(
                            "the DAG's tip {} has no stored body; CURRENT_ROOT is left where it was",
                            tip_hash.to_hex()
                        ),
                    ),
                },
                Err(e) => log.warn(
                    source,
                    &format!(
                        "could not read the tip {} to republish CURRENT_ROOT: {e}",
                        tip_hash.to_hex()
                    ),
                ),
            }
        }
    }

    if let Some(expected) = expected_genesis_hash {
        check_expected_genesis(dag.as_ref(), &expected).await?;
    }

    // The synced root is content-addressed, but its params must also be readable by this binary
    // and agree with this node's admission/proposal configuration before it enters Running.
    // Do this on reconnect and local genesis too, so a restart cannot bypass the restore guard.
    check_running_validation_bounds(
        dag.as_ref(),
        &block_store,
        &approved_store,
        runtime_manager.as_ref(),
        spec.genesis_block_data.min_phlo_price,
        spec.genesis_block_data.max_number_of_parents,
    )
    .await?;
    // The restored allocation gets the same treatment: the imported leaf must be internally
    // consistent, and a joiner that made a local allocation claim must match it. A joiner with no
    // claim (the normal public bootstrap) trusts the chain.
    check_running_dev_vesting(
        dag.as_ref(),
        &block_store,
        &approved_store,
        runtime_manager.as_ref(),
        runtime_manager.genesis_pos().dev_vesting.clone(),
    )
    .await?;

    // **The catch-up window and the driver that walks it** (C259). A node restored at an anchor below
    // its peers' tip cannot ingest the gap through the hash-keyed pull: the walk runs downward from a
    // peer's tip, each block justifies ones inside the gap, and the receiver's pending set saturates
    // (measured: 173 drops, one block validated, frozen 121 against a master's 577). The window narrows
    // the ingest to a couple of windows' worth while the driver walks outward asking for heights;
    // released — by the driver's every exit path, including its first empty answer — the ingest is
    // exactly what it was before, so a node that never catches up is unaffected.
    let catchup = Arc::new(CatchupWindow::new(catchup::WINDOW_HEIGHTS));

    // **The cell the validator path uses to ask for a reset** (F-U5-01's acting half, #320). Installed
    // before the running phase, because the detection happens deep in the validator path — which holds
    // no transport, no block store and no runtime — and the reset is performed *here*, where all three
    // are in scope. The request and the arms it refuses are `interpreter_util`'s.
    let reset_wake = Arc::new(tokio::sync::Notify::new());
    // **This shard's lane** (§107's D4). The cells are process-wide while a node may be a member of
    // several shards, so the key is what keeps a request raised by one shard from reaching another's
    // driver — and once a failed reset stops the node, that misdelivery would be a whole-node kill.
    // `ShardId::to_string()` is the value both halves derive, this side from the `ShardSpec` and the
    // detector's from the same id.
    let shard_lane = spec.shard_id.to_string();
    crate::interpreter_util::install_reset_waker(shard_lane.clone(), reset_wake.clone());

    // The catch-up walk's door. The engine funnels a peer's `BlockRangeRequest` answers down it and the
    // walk owns the receiving end, so a *second* walk needs a second channel — which is why this is a
    // cell the engine reads per answer rather than a sender it owns.
    let block_range_door: crate::engine::node_running::BlockRangeDoor =
        Arc::new(tokio::sync::Mutex::new(tokio::sync::mpsc::channel(4).0));

    // Transition to running mode.
    let engine = NodeRunning::new(
        transport.clone(),
        rp_conf.clone(),
        block_store.clone(),
        dag.clone(),
        block_retriever,
        log.clone(),
        validator_identity_opt,
        incoming_blocks,
        exporter,
        disable_state_exporter,
        catchup.clone(),
        block_range_door.clone(),
    );
    log.info(source, "Making a transition to Running state.");

    // **The anchor this running phase walks to**: the operator's at boot, or the one a reset rewound to.
    let mut phase_anchor = boot_anchor;

    wait_for_first_connection(&connections, log.as_ref()).await;
    comm_util.send_fork_choice_tip_request().await;

    loop {
        start_catchup_if_anchored(
            &mut phase_anchor,
            &block_range_door,
            &catchup,
            &transport,
            &rp_conf,
            &connections,
            &dag,
            &log,
            source,
        )
        .await;

        // **Three exits, not two** (#320). The stream ending is the node shutting down; the reset is a
        // state this node decided it needs, and it is the only one that loops.
        let requested = tokio::select! {
            _ = async {
                let mut tip_refresh = tokio::time::interval(RUNNING_TIP_REFRESH_INTERVAL);
                tip_refresh.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
                // The startup request above has already run. Avoid an extra
                // round at time zero, then reconcile a peer's tip every 30s.
                tip_refresh.tick().await;
                loop {
                    tokio::select! {
                        packet = packet_rx.recv() => {
                            let Some(pm) = packet else { break; };
                            engine.handle(&pm.peer, &pm.message).await;
                        }
                        _ = tip_refresh.tick() => {
                            // A connected-but-previously-unreachable validator
                            // can miss every hash announced during the partition.
                            // Requesting latest heads makes ordinary block
                            // retrieval discover the ancestry it did not hear.
                            comm_util.send_fork_choice_tip_request().await;
                        }
                    }
                }
            } => None,
            _ = reset_wake.notified() => Some(()),
        };
        if requested.is_none() {
            return Ok(());
        }

        // The arm's body, extracted: what a running node does when the waker fires belongs in
        // `engine::reset` with the rest of the reset, and — the reason it is extracted at all — it is
        // then testable without a transport, an importer or a spec, which an `apply`-level test would
        // need a large fixture for while testing five lines of `select!`.
        match crate::engine::reset::act_on_reset_request(
            &shard_lane,
            self_reset,
            &dag,
            &block_store,
            &runtime_manager,
            &log,
            source,
        )
        .await?
        {
            // Nothing pending (a spurious wake), or the switch is off and the node has said so.
            None => continue,
            Some(request) => {
                phase_anchor = Some(request.anchor);
                log.warn(
                    source,
                    &format!(
                        "reset complete: rewound to {} (height {}), the runtime is at that state and the \
                         catch-up walk is restarting from it — the blocks above are re-requested from \
                         {} (#320)",
                        request.anchor.to_hex(),
                        i64::from(request.anchor_height),
                        rp_conf
                            .bootstrap
                            .as_ref()
                            .map(|p| p.endpoint.host.clone())
                            .unwrap_or_else(|| "no peer".to_string()),
                    ),
                );
            }
        }
    }
}

/// Check the restored/startup params before admission and proposal enter the running phase.
pub async fn check_running_validation_bounds(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    approved_store: &ApprovedStore,
    runtime: &RuntimeManager,
    min_phlo_price: i64,
    max_number_of_parents: i32,
) -> Result<(), String> {
    let approved = get_approved_block(approved_store)
        .await?
        .ok_or_else(|| "cannot enter Running without an approved state".to_string())?;
    let params_root = restored_native_state_root(dag, block_store, &approved).await?;
    runtime
        .check_configured_validation_bounds(&params_root, min_phlo_price, max_number_of_parents)
        .await
}

/// **The state whose native leaves the restore guard reads.**
///
/// The approved fringe's `state_hash` is a *fringe* state, not a block's post-state. On a snapshot
/// restore the native leaves (the committed PoS params) live in a block's post-state, and reading the
/// fringe root asks the history for a leaf that was never written there: a good restore is refused
/// with "PoS params leaf not found in committed state".
///
/// **Why the first hash at the highest height is safe.** The committed params are immutable for the
/// life of the chain, so every validated block at the newest height carries the same params in its
/// post-state. Which sibling is chosen therefore cannot change the answer.
async fn restored_native_state_root(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    approved: &FinalizedFringe,
) -> Result<StateHash, String> {
    if approved.hashes.is_empty() {
        // The genesis fringe names the empty pre-state, not the installed PoS descriptors.
        return genesis_post_state_hash(dag, block_store)
            .await?
            .ok_or_else(|| "cannot locate genesis params after restore".to_string());
    }
    let repr = dag.get_representation().await;
    if let Some((_, hashes)) = repr.height_map.iter().next_back() {
        let hash = hashes.first().ok_or_else(|| {
            "restored DAG has a newest height without any block hashes".to_string()
        })?;
        let block = block_store
            .get(&[*hash])
            .await?
            .into_iter()
            .next()
            .flatten()
            .ok_or_else(|| "newest restored DAG block is missing from block storage".to_string())?;
        return Ok(block.post_state_hash);
    }
    // Only a synthetic, empty DAG has no block post-state to inspect.
    // Never silently substitute a fringe root when the DAG names a missing block.
    Ok(approved.state_hash)
}

/// Refuse to enter Running on a different genesis, including when restarting a populated DAG.
async fn check_expected_genesis(
    dag: &dyn BlockDagStorage,
    expected: &BlockHash,
) -> Result<(), String> {
    let repr = dag.get_representation().await;
    check_genesis_height_map(repr.height_map.as_ref(), expected)
}

/// The identity pin is a claim about the *unique block at height zero*, not about
/// whichever block happens to appear first in an incomplete or forked DAG index.
fn check_genesis_height_map(
    heights: &BTreeMap<BlockHeight, BTreeSet<BlockHash>>,
    expected: &BlockHash,
) -> Result<(), String> {
    let roots = heights.get(&BlockHeight::zero()).ok_or_else(|| {
        "expected genesis hash is pinned but the restored DAG has no height-zero genesis; refusing to enter Running".to_string()
    })?;
    if roots.len() != 1 {
        return Err(format!(
            "expected one genesis at height zero, found {}; refusing to enter Running",
            roots.len()
        ));
    }
    let actual = roots.first().ok_or_else(|| {
        "expected genesis hash is pinned but height zero is empty; refusing to enter Running"
            .to_string()
    })?;
    compare_genesis_hash(expected, actual)
}

fn compare_genesis_hash(expected: &BlockHash, actual: &BlockHash) -> Result<(), String> {
    if actual != expected {
        return Err(format!(
            "restored genesis {} differs from pinned genesis {}; refusing to enter Running",
            actual.to_hex(),
            expected.to_hex()
        ));
    }
    Ok(())
}

/// The genesis block's post-state hash, from the restored DAG. `None` when the DAG has no genesis
/// (a synthetic approved state in a guard unit test).
async fn genesis_post_state_hash(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
) -> Result<Option<StateHash>, String> {
    let repr = dag.get_representation().await;
    let Some(genesis_hash) = repr
        .height_map
        .first_key_value()
        .and_then(|(_, hashes)| hashes.first())
    else {
        return Ok(None);
    };
    block_store
        .get(&[*genesis_hash])
        .await?
        .into_iter()
        .next()
        .flatten()
        .ok_or_else(|| "genesis block missing after restore".to_string())
        .map(|block| Some(block.post_state_hash))
}

/// Check the restored developer allocation before admission and proposal enter the running phase.
///
/// **Enforce when present, trust when absent.** A joiner that made a local allocation claim — bonds
/// and wallets files present, and a non-empty `dev-tax-address` — must match the imported genesis.
/// A joiner with no claim carries `None`, which means *no claim*, not *a claim of no allocation*: the
/// normal public-testnet bootstrap restores a chain whose genesis predates the joiner's config, and
/// must not be refused for it.
///
/// **The imported leaf's own schedule is always checked.** At the genesis post-state nothing has
/// vested (`unreleased == allocation`); at any later state the unreleased amount cannot exceed the
/// allocation. A larger one would make `release_dev_tax` compute a negative already-released amount
/// and over-credit the recipient — a silent mint at the next boundary.
pub async fn check_running_dev_vesting(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    approved_store: &ApprovedStore,
    runtime: &RuntimeManager,
    local: Option<(String, NonNegI64)>,
) -> Result<(), String> {
    let approved = get_approved_block(approved_store)
        .await?
        .ok_or_else(|| "cannot enter Running without an approved state".to_string())?;
    let genesis_root = genesis_post_state_hash(dag, block_store).await?;
    // A genesis-only joiner carries `hashes: [genesis_hash]`; the hash comparison, not the fringe
    // shape, is what identifies the genesis state.
    let restored_root = restored_native_state_root(dag, block_store, &approved).await?;
    let at_genesis = genesis_root == Some(restored_root);
    let imported = runtime.committed_dev_vesting(&restored_root).await?;

    if let Some((local_address, local_allocation)) = local {
        match &imported {
            Some(leaf) if leaf.address == local_address && leaf.allocation == local_allocation => {}
            Some(leaf) => {
                return Err(format!(
                    "local developer allocation ({local_address}, {local_allocation:?}) does not \
                     match the restored genesis ({}, {:?}) at state {}; refusing to enter Running",
                    leaf.address,
                    leaf.allocation,
                    hex(restored_root)
                ));
            }
            None => {
                return Err(format!(
                    "local developer allocation ({local_address}, {local_allocation:?}) but the \
                     restored genesis at state {} has none; refusing to enter Running",
                    hex(restored_root)
                ));
            }
        }
    }

    if let Some(leaf) = &imported {
        if at_genesis {
            if leaf.unreleased != leaf.allocation {
                return Err(format!(
                    "restored genesis allocation at state {} has unreleased {:?} of {:?}; refusing \
                     to enter Running",
                    hex(restored_root),
                    leaf.unreleased,
                    leaf.allocation
                ));
            }
        } else if leaf.unreleased > leaf.allocation {
            return Err(format!(
                "restored allocation at state {} has unreleased {:?} of {:?}; refusing to enter \
                 Running",
                hex(restored_root),
                leaf.unreleased,
                leaf.allocation
            ));
        }
    }
    Ok(())
}

fn hex(hash: StateHash) -> String {
    hash.as_bytes()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// Start the catch-up walk for a running phase, if that phase has an anchor and a peer to walk against.
///
/// **Called once per running phase, and that is new** (#320): the boot path starts it an extra time
/// because a reset has just put this node deliberately behind its peers, and the walk is what pulls it
/// back. The engine's door is swapped for the new walk's channel first, which drops the previous
/// sender — and *that* is how the walk that ended learns to stop (`run_catchup` breaks on a closed
/// channel), so the two walks cannot interleave.
#[allow(clippy::too_many_arguments)]
async fn start_catchup_if_anchored(
    phase_anchor: &mut Option<BlockHash>,
    block_range_door: &crate::engine::node_running::BlockRangeDoor,
    catchup: &Arc<CatchupWindow>,
    transport: &Arc<dyn TransportLayer>,
    rp_conf: &RPConf,
    connections: &ConnectionsCell,
    dag: &Arc<dyn BlockDagStorage>,
    log: &Arc<dyn Log>,
    source: LogSource,
) {
    let Some(anchor) = phase_anchor.take() else {
        return;
    };
    // **Only a node that named an anchor catches up.** An ordinary joiner is level with the fringe it
    // synced to; its first window would come back empty and the driver would release the gate having
    // done nothing, which is a round trip this avoids. If there is no bootstrap there is nobody to
    // walk against, so the driver is not started and the receive end is dropped with it.
    let Some(peer) = rp_conf.bootstrap.clone() else {
        log.warn(
            source,
            &format!(
                "an anchor ({}) was named without a bootstrap: nothing to catch up against",
                anchor.to_hex()
            ),
        );
        return;
    };
    let (block_range_tx, block_range_rx) = tokio::sync::mpsc::channel(4);
    *block_range_door.lock().await = block_range_tx;
    let (transport, conf, connections, dag, log, catchup) = (
        transport.clone(),
        rp_conf.clone(),
        connections.clone(),
        dag.clone(),
        log.clone(),
        catchup.clone(),
    );
    tokio::spawn(async move {
        catchup::run_catchup(
            transport,
            conf,
            connections,
            dag,
            log,
            catchup,
            peer,
            block_range_rx,
        )
        .await;
    });
}

