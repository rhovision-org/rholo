/// **The ceremony identity the inputs force** (issue #456, Law 84): the bonds file's first bond.
///
/// The local validator's key is used when it *is* that bond. The autogenerated-bonds path writes a
/// `<public_key>.sk` beside the bonds file for every generated validator, so the first bond's key is
/// available there; a network node, which has neither, refuses rather than create a private chain —
/// exactly the failure the retired `rnode-c` lived in for a month.
fn resolve_genesis_ceremony(
    bonds_path: &str,
    local: &ValidatorIdentity,
) -> Result<(PublicKey, ValidatorIdentity), String> {
    let first = bonds_parser::first_bond(Path::new(bonds_path))?;
    if local.public_key == first {
        return Ok((first, local.clone()));
    }
    if let Some(identity) = generated_ceremony_identity(bonds_path, &first) {
        return Ok((first, identity));
    }
    Err(format!(
        "the genesis ceremony must be run by the first bonded validator (issue #456): the bonds \
         file's first entry is {}, this node's key is {}. Refusing to create a local genesis — \
         start with --bootstrap to join the existing chain.",
        base16::encode(first.bytes()),
        base16::encode(local.public_key.bytes())
    ))
}

/// The autogen ceremony key: `<first bond>.sk` beside the bonds file, if it exists and derives that
/// bond's public key.
fn generated_ceremony_identity(bonds_path: &str, first: &PublicKey) -> Option<ValidatorIdentity> {
    let path = Path::new(bonds_path);
    let sk = path
        .parent()?
        .join(format!("{}.sk", base16::encode(first.bytes())));
    let hex = std::fs::read_to_string(sk).ok()?;
    let bytes = base16::decode(hex.trim())?;
    let identity = ValidatorIdentity::from_private_key(PrivateKey::new(bytes)).ok()?;
    (identity.public_key == *first).then_some(identity)
}

pub async fn create_genesis_block(
    validator: &ValidatorIdentity,
    shard_id: &str,
    block_number: i64,
    bonds_path: &str,
    autogen_shard_size: i32,
    vaults_path: &str,
    minimum_bond: i64,
    maximum_bond: i64,
    epoch_length: i32,
    quarantine_length: i32,
    number_of_active_validators: i32,
    executor_share: NonNegI64,
    absence_slack: NonNegI64,
    participation_grace: NonNegI64,
    min_phlo_price: NonNegI64,
    max_number_of_parents: i64,
    pos_multi_sig_public_keys: &[String],
    pos_multi_sig_quorum: i32,
    pos_vault_pub_key: &str,
    system_contract_pub_key: &str,
    dev_tax_address: &str,
    dev_tax_vesting_blocks: i64,
    liveness_absence_threshold: i64,
    liveness_jail_after_boundaries: i64,
    liveness_jail_epochs: i64,
    liveness_vote_window: i64,
    liveness_slash_severity: i64,
    runtime: &RuntimeManager,
) -> Result<BlockMessage, String> {
    // Initial REV vaults, with the developer allocation derived from their total (Law 78). This is
    // the same derivation `genesis_descriptors_from_config` applies, so the block this ceremony
    // creates and the descriptors every node replays carry the same vaults — and the same genesis
    // post-state hash.
    let vaults = vault_parser::parse(Path::new(vaults_path))?;
    // The developer allocation is *derived* from the parsed vaults and rides into the genesis as a
    // vesting account, exactly where `genesis_descriptors_from_config` derives it, so the block this
    // ceremony creates and the descriptors every node replays carry the same value (Laws 78–79).
    let dev_vesting = crate::genesis::dev_allocation(&vaults, dev_tax_address)?;

    // Initial validators.
    let bonds = bonds_parser::parse_or_generate(Path::new(bonds_path), autogen_shard_size)?;
    // **The inputs force the ceremony's identity** (issue #456, Law 84): the first bond in the file.
    // Its key signs the blessed deploys and fills the block's `sender`, and both enter the block
    // hash, so any other local key would produce a different genesis — a private chain.
    let (first_bond, ceremony) = resolve_genesis_ceremony(bonds_path, validator)?;
    let validators: Vec<Validator> = bonds
        .into_iter()
        .map(|(pk, stake)| Validator { pk, stake })
        .collect();

    // Run the genesis deploys and create the block.
    let genesis = Genesis {
        sender: first_bond,
        shard_id: shard_id.to_string(),
        block_number,
        proof_of_stake: ProofOfStake {
            // The config is where a signed number becomes a protocol parameter, so this is where a
            // negative one is refused rather than carried (deferred item 1d). Not clamped: "no
            // minimum" and "a minimum of -1" are different intentions, and only one of them is
            // expressible here.
            minimum_bond: NonNegI64::try_from(minimum_bond)
                .map_err(|e| format!("casper.genesis.bond-minimum must not be negative: {e}"))?,
            maximum_bond: NonNegI64::try_from(maximum_bond)
                .map_err(|e| format!("casper.genesis.bond-maximum must not be negative: {e}"))?,
            validators,
            epoch_length,
            quarantine_length,
            number_of_active_validators,
            executor_share,
            absence_slack,
            participation_grace,
            min_phlo_price,
            max_number_of_parents,
            pos_multi_sig_public_keys: pos_multi_sig_public_keys.to_vec(),
            pos_multi_sig_quorum,
            pos_vault_pub_key: pos_vault_pub_key.to_string(),
            dev_tax_vesting_blocks: NonNegI64::try_from(dev_tax_vesting_blocks).map_err(|e| {
                format!("casper.genesis.dev-tax-vesting-blocks must not be negative: {e}")
            })?,

            liveness_absence_threshold,
            liveness_jail_after_boundaries,
            liveness_jail_epochs,
            liveness_vote_window,
            liveness_slash_severity,
        },
        registry: Registry {
            system_contract_pub_key: system_contract_pub_key.to_string(),
        },
        vaults,
        dev_vesting,
    };

    // The liveness config is all-or-nothing, and this is the other path that turns config into
    // consensus state: refuse an incoherent one before the genesis block is signed.
    crate::genesis::build_pos_genesis(&genesis.proof_of_stake, genesis.dev_vesting.clone())
        .params
        .validate()?;
    crate::genesis::create_genesis_block(&ceremony, &genesis, runtime).await
}

/// Create one shard's genesis block from its [`ShardSpec`] (port of
/// `NodeLaunch.createGenesisBlockFromConfig`).
pub async fn create_genesis_block_from_config(
    validator: &ValidatorIdentity,
    spec: &ShardSpec,
    runtime: &RuntimeManager,
) -> Result<BlockMessage, String> {
    let gbd = &spec.genesis_block_data;
    // The block's shard id is the spec's validated *full* id (`{parent-shard-id}/{shard-name}`),
    // matching the proposer (`Proposer::apply`), the block receiver's `check_if_of_interest` and
    // both deploy APIs. Passing the bare `shard_name` here made the genesis block carry an id
    // ("root") that no later block or deploy shares ("/root"), so a genesis block received from a
    // peer was dropped by the receiver's equality check.
    let shard_id = spec.shard_id.to_string();
    // The producer's share, refused rather than clamped like the bond bounds: a share over the whole
    // would pay a producer more than the deploy burned, out of the stake the same vault holds for
    // every other validator.
    let executor_share = NonNegI64::try_from(i64::from(gbd.executor_share))
        .map_err(|e| format!("casper.genesis.executor-share must not be negative: {e}"))?;
    if i64::from(executor_share) > 10_000 {
        return Err(format!(
            "casper.genesis.executor-share is {} basis points, above the whole of what a deploy burns",
            i64::from(executor_share)
        ));
    }
    let absence_slack = NonNegI64::try_from(i64::from(gbd.absence_slack))
        .map_err(|e| format!("casper.genesis.absence-slack must not be negative: {e}"))?;
    // The "absent means the binary rule" reading has already been applied where this `gbd` was parsed
    // (`configuration::hocon`), so this is the value and not a second fallback.
    let participation_grace = NonNegI64::try_from(i64::from(gbd.participation_grace))
        .map_err(|e| format!("casper.genesis.participation-grace must not be negative: {e}"))?;
    // The fee floor is committed rather than only configured (see `PosParams::min_phlo_price`), so a
    // negative one is refused here like the other genesis numbers: "no floor" is `0`.
    let min_phlo_price = NonNegI64::try_from(gbd.min_phlo_price)
        .map_err(|e| format!("casper.min-phlo-price must not be negative: {e}"))?;
    create_genesis_block(
        validator,
        &shard_id,
        gbd.genesis_block_number,
        &gbd.bonds_file,
        spec.autogen_shard_size,
        &gbd.wallets_file,
        gbd.bond_minimum,
        gbd.bond_maximum,
        gbd.epoch_length,
        gbd.quarantine_length,
        gbd.number_of_active_validators,
        executor_share,
        absence_slack,
        participation_grace,
        min_phlo_price,
        i64::from(gbd.max_number_of_parents),
        &gbd.pos_multi_sig_public_keys,
        gbd.pos_multi_sig_quorum,
        &gbd.pos_vault_pub_key,
        &gbd.system_contract_pub_key,
        &gbd.dev_tax_address,
        gbd.dev_tax_vesting_blocks,
        gbd.liveness_absence_threshold,
        i64::from(gbd.liveness_jail_after_boundaries),
        i64::from(gbd.liveness_jail_epochs),
        i64::from(gbd.liveness_vote_window),
        i64::from(gbd.liveness_slash_severity),
        runtime,
    )
    .await
}

/// Wait until at least one peer connection is established (port of `waitForFirstConnection`).
async fn wait_for_first_connection(connections: &ConnectionsCell, log: &dyn Log) {
    let source = LogSource::new("casper.engine.NodeLaunch");
    loop {
        if !connections.read().await.is_empty() {
            return;
        }
        log.debug(source, "Waiting for first connection...");
        tokio::time::sleep(Duration::from_millis(250)).await;
    }
}

/// Create, store and broadcast one shard's genesis block (port of
/// `createStoreBroadcastGenesis`).
async fn create_store_broadcast_genesis(
    validator_identity_opt: Option<&ValidatorIdentity>,
    spec: &ShardSpec,
    runtime_manager: &RuntimeManager,
    block_store: &BlockStore,
    approved_store: &ApprovedStore,
    dag: &dyn BlockDagStorage,
    comm_util: &CommUtil,
    log: &dyn Log,
) -> Result<BlockMessage, String> {
    let source = LogSource::new("casper.engine.NodeLaunch");
    let validator = validator_identity_opt.ok_or_else(|| {
        "To create genesis block node must provide validator private key".to_string()
    })?;

    let genesis_block = create_genesis_block_from_config(validator, spec, runtime_manager).await?;
    log.info(
        source,
        &format!(
            "Sending genesis block {} to peers...",
            genesis_block.block_hash.to_hex()
        ),
    );

    let genesis_fringe = FinalizedFringe {
        hashes: Vec::new(),
        state_hash: genesis_block.pre_state_hash,
        ancestry: Vec::new(),
    };

    put_block(block_store, genesis_block.clone()).await?;
    put_approved_block(approved_store, genesis_fringe.clone()).await?;
    let genesis_post = genesis_block.post_state_hash;
    insert_genesis(dag, genesis_block.clone()).await?;
    // **The genesis block is accepted: publish its state** (law 80, B40). Its checkpoint recorded the
    // root as known; without this the pointer would stay at the empty root until the first accepted
    // block.
    if let Err(e) = runtime_manager
        .publish_accepted_root(Blake2b256Hash::from_byte_array(genesis_post.as_bytes()))
        .await
    {
        log.warn(source, &format!("could not publish the genesis root: {e}"));
    }
    for outcome in comm_util
        .stream_to_peers(&FinalizedFringeSerde.mk_packet(&genesis_fringe), None)
        .await
    {
        if let Err(error) = outcome {
            log.warn(
                source,
                &format!("the genesis fringe stream failed: {error:?}"),
            );
        }
    }
    Ok(genesis_block)
}

/// The node launch mode dispatch (port of `NodeLaunch.apply`).
#[allow(clippy::too_many_arguments)]
pub async fn apply<
    I: RSpaceImporter + Send + 'static,
    E: RSpaceExporter + Send + Sync + 'static,
>(
    mut packet_rx: mpsc::Receiver<PeerMessage>,
    incoming_blocks: mpsc::Sender<BlockMessage>,
    spec: ShardSpec,
    trim_state: bool,
    // **An operator-named block to sync to instead of a finalised fringe** (C259). See
    // `CasperConf::sync_anchor`; only consulted when this node's DAG is empty.
    sync_anchor: Option<String>,
    expected_genesis_hash: Option<String>,
    // **May this node reset itself?** (F-U5-01's acting half, #320.) Off means the detector still
    // counts, logs and dry-runs the divergence but nothing acts on it — the behaviour of every build
    // before this one. See `CasperConf::self_reset` for why it is an operator switch and not automatic.
    self_reset: bool,
    // **May a self-replay fault reset this node?** (#564) On by default; see
    // `CasperConf::self_replay_reset` for the constructive safety case. Off means the fault halts.
    self_replay_reset: bool,
    // **Fetch the bodies of a certified history in the background** (default on). Off is the
    // light-node mode: the node serves from the checkpoint state and reports its history floor.
    backfill_bodies: bool,
    // **The wake a completed self-replay reset needs** (#564, F-U23-11). The running loop owns the
    // moment the catch-up walk passes the anchor it rewound to; the health cell behind the operator
    // surface owns the latch. This is the narrow seam, not a process-wide cell.
    self_replay_resume: Arc<dyn crate::engine::reset::SelfReplayResume>,
    // Operator switch, threaded to `NodeRunning`: when set, this node refuses store-items
    // (state-sync) requests (port of the Scala's `disableStateExporter`).
    disable_state_exporter: bool,
    // **The inbound consumer pool's width** (`protocol-server.max-message-consumers`). The Scala
    // answered peer messages with N concurrent consumers; the Rust port handled them one at a time
    // under the shard loop, so one store-items page or one block stream blocked every other sync
    // request behind it. `0` is clamped to 1 (serial, the old behaviour).
    max_message_consumers: usize,
    validator_identity_opt: Option<ValidatorIdentity>,
    // **The sequences this node's key has observed on the network** (Law 124). Shared with the
    // proposer, which refuses to sign or announce through a claim; `None` for a non-validator.
    received_claims: Option<Arc<crate::blocks::received_claims::ReceivedClaims>>,
    standalone: bool,
    // **Whether the node was started in dev mode.** Consulted only at the genesis-creation branch
    // below, and only to decide whether an unset `dev-tax-address` is a refusal (Law 78). Devnets run
    // in dev mode — `tools/devnet.sh` starts every node it launches with `--dev-mode` — so the gate
    // bites on a production genesis and nowhere else.
    dev_mode: bool,
    transport: Arc<dyn TransportLayer>,
    comm_util: Arc<CommUtil>,
    block_retriever: Arc<BlockRetriever>,
    connections: ConnectionsCell,
    rp_conf: RPConf,
    runtime_manager: Arc<RuntimeManager>,
    block_store: BlockStore,
    approved_store: ApprovedStore,
    // **The accepted certificates, for boot re-verification and for serving the next joiner**
    // (sync/verification separation). The sync branch persists the certificate it verified here.
    checkpoint_store: rchain_block_storage::checkpoint_store::CheckpointStore,
    dag: Arc<dyn BlockDagStorage>,
    block_disposition: BlockDispositionStore,
    to_processor: mpsc::Sender<BlockMessage>,
    importer: I,
    exporter: E,
    phase: crate::engine::node_phase::NodePhaseCell,
    // **Where a joiner fetches the checkpoint certificate** (sync/verification separation). The
    // engine owns the sync protocol and has no HTTP client; the node wires the bootstrap's client
    // endpoint. `None` makes sync fail closed: a fringe is not a state root without a quorum.
    checkpoint_source: Option<Arc<dyn crate::engine::checkpoint_source::CheckpointSource>>,
    // **The runtime's admissible pre-state window** (review R2). Installed below from the accepted
    // anchor; `None` until then is a retryable fault for any block that arrives early.
    accepted_window: crate::engine::anchor::SharedAcceptedWindow,
    log: Arc<dyn Log>,
) -> Result<(), String> {
    let source = LogSource::new("casper.engine.NodeLaunch");
    // **The phase cell is written by this shard's launch and only by it** (B47). A restart begins
    // at `Starting`; the sync branch below moves to `Syncing`, and the transition to the running
    // engine at the end of this function moves to `Running`. The disposition loops hold a clone and
    // wait for `Running`, so a start-up re-offer cannot race a recovery into the live DAG.
    phase.set_phase(crate::engine::node_phase::NodePhase::Starting);

    // **The operator's anchor, parsed once** (C259): the sync phase names it in its fringe request, and
    // the running phase walks to it. Parsed here rather than in the branch because a `--sync-anchor` typo
    // must be refused whatever this node's DAG looks like — the boot path is not the only reader now.
    let mut boot_anchor = match sync_anchor.as_deref() {
        None => None,
        Some(hex) => Some(
            BlockHash::try_from_hex(hex)
                .map_err(|e| format!("--sync-anchor `{hex}` is not a block hash: {e}"))?,
        ),
    };

    let expected_genesis_hash = expected_genesis_hash
        .as_deref()
        .map(|hash| {
            BlockHash::try_from_hex(hash)
                .map_err(|e| format!("--expected-genesis-hash `{hash}` is invalid: {e}"))
        })
        .transpose()?;
    let repr = dag.get_representation().await;
    let pending_recovery = approved_store
        .get(&[RECOVERY_PENDING_KEY])
        .await?
        .into_iter()
        .next()
        .flatten();
    // A pending/faulted body is owned by its ledger row (Law 88a). Block immediately only for
    // identities that have neither durable owner; cardinality alone also counts ordinary work.
    let unaccounted =
        crate::block_disposition::unaccounted_stored_bodies(&block_disposition, &block_store, &dag)
            .await?;
    if crate::block_disposition::observe_boot_orphans(unaccounted.len()) > 0 {
        log.warn(
            source,
            &format!(
                "boot: {} stored bodies have neither a DAG entry nor a disposition (U19/B46)",
                unaccounted.len()
            ),
        );
    }
    // **The accepted state this boot will run from** (Law 108). Each branch must set it; the boot
    // refuses to run without one, so there is no heuristic root fallback.
    let mut accepted_state: Option<crate::engine::anchor::AcceptedState> = None;
    // **The join ladder's boot side** (RC-4). An empty DAG, a pending recovery, and a reconnect
    // whose accepted fringe no certificate anchors all enter the *same* checkpoint sync; the flag
    // is set here and cleared when a boot has an anchor it can run from. The sync body below is the
    // one engine loop — a light join is not a fourth sync path.
    let mut needs_sync = repr.dag_set.is_empty() || pending_recovery.is_some();
    // A reconnect behind its peers: the sync restores the certified anchor and the node runs from
    // that, not from the stale fence. Eligibility is decided by the agreement below; the sync
    // fetches and verifies the statement itself.
    let mut light_join = false;
    let mut light_join_eligible = false;
    // Written only once the sync's outcome is known (`light-join` or `light-join-failed`).
    let mut pending_decision: Option<BootDecision> = None;
    if repr.dag_set.is_empty() && standalone && pending_recovery.is_none() {
        needs_sync = false;
        if expected_genesis_hash.is_some() {
            return Err(
                "a pinned network genesis cannot be created by a standalone node".to_string(),
            );
        }
        // **The last point at which the developer allocation is still decidable** (Law 78). A genesis
        // vault cannot be added afterwards without a hard fork, so an unset address is refused *here*,
        // where the node is about to build genesis and the operator can still act. The condition and
        // its sentence live in `dev_tax`, next to the rule, so a test drives them without a node; what
        // this branch supplies is the context — being reachable only when the DAG is empty is what
        // keeps a standalone node *restarting* onto a chain it built (the public testnet's bootstrap,
        // whose genesis predates this key) from being refused for a decision it already made.
        crate::genesis::dev_tax::refuse_a_production_genesis_without_an_address(
            dev_mode,
            &spec.genesis_block_data.dev_tax_address,
        )?;
        crate::genesis::dev_tax::refuse_a_production_genesis_with_a_zero_vesting_term(
            dev_mode,
            &spec.genesis_block_data.dev_tax_address,
            spec.genesis_block_data.dev_tax_vesting_blocks,
        )?;
        log.info(
            source,
            "Starting as genesis master, creating genesis block...",
        );
        let genesis_block = create_store_broadcast_genesis(
            validator_identity_opt.as_ref(),
            &spec,
            runtime_manager.as_ref(),
            &block_store,
            &approved_store,
            dag.as_ref(),
            comm_util.as_ref(),
            log.as_ref(),
        )
        .await?;
        // The genesis master's anchor is the genesis it just created from the configuration. Law 108
        // requires the anchor's root; the creation path has already published it.
        let pin = crate::engine::anchor::GenesisPin {
            block: genesis_block.block_hash,
            post_state: genesis_block.post_state_hash,
        };
        accepted_state = Some(crate::engine::anchor::AcceptedState::from_genesis(
            pin,
            &genesis_block,
        )?);
    } else if !repr.dag_set.is_empty() && pending_recovery.is_none() {
        // **A node that reset itself is not simply reconnecting** (F-U5-01's crash window, register
        // C274; law 72). Its DAG was deliberately truncated to an anchor, so running on what it holds
        // would be running on a chain it chose to leave — and if the process died part-way through the
        // reset's durable effects, its block store holds bodies the DAG does not, which the receiver
        // reads as *"stored but not yet validated"* and re-injects above the anchor. `resume_after_reset`
        // re-applies **every** effect the completion record brackets — the two stores and the runtime
        // root — and names the anchor the catch-up walk below must start from. With no marker this is the
        // ordinary reconnection it has always been.
        if let Some(anchor) = crate::engine::reset::resume_after_reset(
            &dag,
            &block_store,
            &runtime_manager,
            &log,
            source,
        )
        .await?
        {
            // **A contradicting pair is refused, not resolved with a warning** (W-N11-01): see
            // [`crate::engine::reset::boot_anchor_after_reset`] for why the record wins and why
            // picking in silence is the defect — on a store the operator did not create, the record
            // is a planted restore point.
            boot_anchor = Some(crate::engine::reset::boot_anchor_after_reset(
                boot_anchor,
                anchor,
            )?);
        } else {
            log.info(source, "Reconnecting to existing network...");
        }

        // **The accepted fringe is re-verified against its stored certificate at boot**
        // (sync/verification separation). The state on disk was accepted under a quorum; a restart
        // must not turn a corrupted or replaced certificate into an accepted history. Only a
        // certificate naming *this* fringe is evidence for it — an older certificate is what the
        // node held when it last certified, and the accepted fringe may legitimately be newer.
        // **A node that synced before the certificate was persisted has none stored.** Pull the
        // configured source's verified certificate and adopt it; this is the same bootstrap pull
        // the sync branch trusts. No stored certificate and no source leaves `None`; a non-genesis
        // DAG then refuses by name below.
        let shard_id = spec.shard_id.to_string();
        let genesis_only = repr.dag_set.len() == 1
            && repr
                .height_map
                .keys()
                .next()
                .map(|height| i64::from(*height))
                == Some(0);
        let store_head = checkpoint_store.latest().await?.map(|certificate| {
            crate::checkpoint::checkpoint_digest(&certificate.checkpoint)
                .map(|digest| digest.to_hex())
                .unwrap_or_else(|_| "malformed".to_string())
        });
        // **The accepted fringe the boot must anchor** (Law 108). It is also the hint a restart
        // behind its peers gives the source: the head certificate may be *ahead* of this fringe,
        // and a certificate for an anchor in it is what the agreement below can accept.
        let recorded_fringe: Option<BTreeSet<BlockHash>> = approved_store
            .get(&[rchain_block_storage::approved_store::FINALIZED_FRINGE_KEY])
            .await?
            .into_iter()
            .next()
            .flatten()
            .map(|accepted| accepted.hashes.iter().copied().collect());
        let acquisition = acquire_boot_certificate(
            &checkpoint_store,
            checkpoint_source.as_ref(),
            &runtime_manager.genesis_pos().bonds,
            &shard_id,
            recorded_fringe.as_ref(),
        )
        .await;
        let outcome = boot_outcome(genesis_only, &acquisition);
        write_boot_trace(&BootTrace {
            kind: "boot".to_string(),
            stage: "acquisition".to_string(),
            dag_len: repr.dag_set.len(),
            genesis_only,
            store_head: store_head.clone(),
            source_configured: checkpoint_source.is_some(),
            acquisition: match &acquisition {
                Ok(Some(_)) => "certificate".to_string(),
                Ok(None) => "none".to_string(),
                Err(error) => format!("refused: {error}"),
            },
            served_digest: acquisition
                .as_ref()
                .ok()
                .and_then(|certificate| certificate.as_ref())
                .map(|certificate| certificate.verified.digest.to_hex()),
            served_anchor: acquisition
                .as_ref()
                .ok()
                .and_then(|certificate| certificate.as_ref())
                .map(|certificate| certificate.verified.checkpoint.anchor.clone()),
            served_shard: acquisition
                .as_ref()
                .ok()
                .and_then(|certificate| certificate.as_ref())
                .map(|certificate| certificate.verified.checkpoint.shard_id.clone()),
            shard_id: shard_id.clone(),
            served_supporting_stake: acquisition
                .as_ref()
                .ok()
                .and_then(|certificate| certificate.as_ref())
                .map(|certificate| certificate.verified.supporting_stake),
            served_total_stake: acquisition
                .as_ref()
                .ok()
                .and_then(|certificate| certificate.as_ref())
                .map(|certificate| certificate.verified.total_stake),
            outcome: match outcome {
                BootOutcome::Genesis => "genesis".to_string(),
                BootOutcome::Certified => "certified".to_string(),
                BootOutcome::Refused(_) => "refused".to_string(),
            },
            refusal_coordinate: match outcome {
                BootOutcome::Refused(coordinate) => Some(coordinate.as_str().to_string()),
                _ => None,
            },
            accepted: acquisition.as_ref().ok().is_some_and(Option::is_some) || genesis_only,
            fringe_agrees: None,
            anchor_closure_present: None,
            fringe_agreement: None,
            accepted_fringe: None,
            certified_fringe: None,
            recovery: None,
        });
        // **The acquisition is not the decision.** Keep what the decision trace needs before the
        // certificate is consumed; `accepted` on the acquisition trace says only that a verified
        // certificate was found, not that the accepted fringe is anchored by it.
        let acquisition_summary = match &acquisition {
            Ok(Some(_)) => "certificate".to_string(),
            Ok(None) => "none".to_string(),
            Err(error) => format!("refused: {error}"),
        };
        let served_digest = acquisition
            .as_ref()
            .ok()
            .and_then(|certificate| certificate.as_ref())
            .map(|certificate| certificate.verified.digest.to_hex());
        let served_anchor = acquisition
            .as_ref()
            .ok()
            .and_then(|certificate| certificate.as_ref())
            .map(|certificate| certificate.verified.checkpoint.anchor.clone());
        let served_shard = acquisition
            .as_ref()
            .ok()
            .and_then(|certificate| certificate.as_ref())
            .map(|certificate| certificate.verified.checkpoint.shard_id.clone());
        let served_supporting_stake = acquisition
            .as_ref()
            .ok()
            .and_then(|certificate| certificate.as_ref())
            .map(|certificate| certificate.verified.supporting_stake);
        let served_total_stake = acquisition
            .as_ref()
            .ok()
            .and_then(|certificate| certificate.as_ref())
            .map(|certificate| certificate.verified.total_stake);
        let mut fringe_agreement: Option<String> = if genesis_only {
            Some("genesis".to_string())
        } else {
            None
        };
        let mut accepted_fringe: Option<usize> = None;
        let mut certified_fringe: Option<usize> = None;
        let boot_certificate = acquisition?;
        if let Some(BootCertificate {
            verified,
            source: certificate_source,
            ..
        }) = boot_certificate
        {
            if certificate_source == BootCertificateSource::Fetched {
                log.warn(
                    source,
                    &format!(
                        "boot: no checkpoint certificate was stored; fetched and adopted the \
                         configured source's verified certificate {}",
                        verified.digest.to_hex()
                    ),
                );
            }
            let recorded = recorded_fringe;
            let certified_set: BTreeSet<_> = verified
                .checkpoint
                .fringe_hashes
                .iter()
                .filter_map(|hex| {
                    rchain_shared::base16::decode(hex)
                        .and_then(|bytes| BlockHash::try_from(bytes.as_slice()).ok())
                })
                .collect();
            accepted_fringe = recorded.as_ref().map(BTreeSet::len);
            certified_fringe = Some(certified_set.len());
            match stored_fringe_agreement(recorded.as_ref(), &certified_set) {
                StoredFringeAgreement::Reverified => {
                    fringe_agreement = Some("reverified".to_string());
                    log.info(
                        source,
                        &format!(
                            "boot: the accepted fringe ({} block(s)) is re-verified by its stored \
                             checkpoint certificate at anchor {}",
                            certified_set.len(),
                            verified.checkpoint.anchor_height
                        ),
                    );
                    // **The stored certificate is the anchor** (Law 108): its checkpoint root is the
                    // root this node runs from. Since the merge-base correction, that root is the **merge base** — the
                    // state at the fringe the anchor itself finalised, which is where a post-anchor
                    // block's merge starts — so the approved fringe's state and the certificate's
                    // root agree by construction rather than being two different claims.
                    let window = rebuild_window_for_boot(
                        dag.as_ref(),
                        &verified,
                        certificate_source == BootCertificateSource::Fetched,
                    )
                    .await?;
                    accepted_state = Some(crate::engine::anchor::AcceptedState::from_certificate(
                        verified.clone(),
                        window,
                    )?);
                }
                StoredFringeAgreement::Mismatch {
                    certified,
                    accepted,
                } => {
                    // **A newer accepted fringe is not a disagreement when it descends from the
                    // certificate's anchor.** The certificate is a snapshot; the approved store
                    // records the tip at shutdown. Refusing every later tip is the in-place-restart
                    // stall: the validator can never boot again. The certificate still anchors the
                    // history (its closure and commitments are re-verified below), and
                    // `seed_derived_roots` re-seeds the validated blocks above it. A recorded
                    // fringe that does **not** descend from the anchor is a fork and is refused.
                    let anchor =
                        BlockHash::try_from_hex(&verified.checkpoint.anchor).map_err(|e| {
                            format!("the stored certificate's anchor is not a block hash: {e}")
                        })?;
                    let descends = match recorded.as_ref() {
                        Some(recorded) => {
                            fringe_descends_from(dag.as_ref(), recorded, anchor).await?
                        }
                        None => false,
                    };
                    if descends {
                        fringe_agreement = Some("descendant".to_string());
                        log.warn(
                            source,
                            &format!(
                                "boot: the accepted fringe ({accepted} block(s)) is a validated \
                                 descendant of the certificate's fringe ({certified} block(s)); \
                                 adopting the certificate as the base and re-deriving the window"
                            ),
                        );
                        let window = rebuild_window_for_boot(
                            dag.as_ref(),
                            &verified,
                            certificate_source == BootCertificateSource::Fetched,
                        )
                        .await?;
                        accepted_state =
                            Some(crate::engine::anchor::AcceptedState::from_certificate(
                                verified.clone(),
                                window,
                            )?);
                    } else {
                        fringe_agreement = Some("mismatch".to_string());
                        log.warn(
                            source,
                            &format!(
                                "boot: the stored checkpoint certificate names another fringe than \
                                 the accepted fringe ({certified} certified, {accepted} accepted) \
                                 and the accepted fringe does not descend from its anchor; the \
                                 accepted state is not re-verified by it"
                            ),
                        );
                        // **A fetched certificate that does not anchor the fence is the light-join
                        // case** (RC-4): the node's own statement cannot be re-verified, but the
                        // network's quorum statement can be adopted. A *stored* certificate is the
                        // node's own history; its disagreement is a local inconsistency and stays a
                        // refusal.
                        if certificate_source == BootCertificateSource::Fetched {
                            light_join_eligible = true;
                        }
                    }
                }
                StoredFringeAgreement::Absent => {
                    fringe_agreement = Some("absent".to_string());
                    // **No accepted fringe is recorded, but a verified certificate is.** A genesis
                    // master — and a node whose approved-fringe write was interrupted — has no
                    // fringe to compare against; the certificate is the only accepted-state record
                    // and is adopted as the anchor (Law 108). The DAG must still hold the anchor's
                    // closure, which the window rebuild verifies.
                    log.warn(
                        source,
                        "boot: no accepted fringe is recorded; adopting the verified stored \
                         checkpoint certificate as the anchor",
                    );
                    let window = rebuild_window_for_boot(
                        dag.as_ref(),
                        &verified,
                        certificate_source == BootCertificateSource::Fetched,
                    )
                    .await?;
                    accepted_state = Some(crate::engine::anchor::AcceptedState::from_certificate(
                        verified.clone(),
                        window,
                    )?);
                }
            }
        } else {
            if !genesis_only {
                return Err(format!(
                    "this node's DAG holds {} block(s) but no checkpoint certificate is stored and \
                     no checkpoint source is configured; the accepted state cannot be attributed",
                    repr.dag_set.len()
                ));
            }
            log.info(
                source,
                "boot: no checkpoint certificate is stored for the accepted fringe; a genesis-only \
                 DAG can still be anchored by its pinned genesis",
            );
        }

        // **The decision is what the trace must carry.** The acquisition trace above says a
        // verified certificate was found; it does not say the accepted fringe is anchored by it.
        // A quorate certificate whose anchor is ahead of the accepted fringe (a restart that was
        // down while the fence moved) refuses here, and `accepted` on the acquisition trace alone
        // would read as a safe boot.
        let decision = BootDecision {
            dag_len: repr.dag_set.len(),
            genesis_only,
            store_head: store_head.clone(),
            source_configured: checkpoint_source.is_some(),
            acquisition: acquisition_summary.clone(),
            served_digest: served_digest.clone(),
            served_anchor: served_anchor.clone(),
            served_shard: served_shard.clone(),
            shard_id: shard_id.clone(),
            served_supporting_stake,
            served_total_stake,
            fringe_agreement: fringe_agreement.clone(),
            accepted_fringe,
            certified_fringe,
        };

        // **No verified certificate: only a genesis-only DAG has an anchor left.** A DAG with any
        // block above genesis and no certificate is an unattributed state; the node refuses to run
        // rather than serve it (Law 108).
        if accepted_state.is_none() {
            let genesis_only = repr.dag_set.len() == 1
                && repr
                    .height_map
                    .keys()
                    .next()
                    .map(|height| i64::from(*height))
                    == Some(0);
            if genesis_only {
                let genesis_hash = repr
                    .height_map
                    .values()
                    .next()
                    .and_then(|hashes| hashes.iter().next().copied())
                    .ok_or_else(|| "the DAG names no genesis block".to_string())?;
                let genesis_post = genesis_post_state_hash(dag.as_ref(), &block_store)
                    .await?
                    .ok_or_else(|| {
                        "the genesis block has no recorded post-state, so it cannot anchor this \
                         node"
                            .to_string()
                    })?;
                let genesis_block = block_store
                    .get(&[genesis_hash])
                    .await?
                    .into_iter()
                    .flatten()
                    .next()
                    .ok_or_else(|| "the genesis block has no stored body".to_string())?;
                // **The operator's pin is checked before any accepted state exists** (review R5).
                // `from_genesis` also refuses a body that is not the pin, but it words that refusal
                // differently; the canonical `differs from pinned genesis` sentence belongs to the
                // pin check, so the check runs first and the state then carries the proven identity.
                if let Some(expected) = expected_genesis_hash {
                    check_expected_genesis(dag.as_ref(), &expected).await?;
                }
                let pin = crate::engine::anchor::GenesisPin {
                    block: expected_genesis_hash.unwrap_or(genesis_hash),
                    post_state: genesis_post,
                };
                accepted_state = Some(crate::engine::anchor::AcceptedState::from_genesis(
                    pin,
                    &genesis_block,
                )?);
            } else if light_join_eligible {
                // **A restart behind its peers joins light** (RC-4, the join ladder). The fetched
                // certificate verified but does not anchor the accepted fringe: the fence is behind
                // the network's finality, or on a branch the network's quorum statement does not
                // contain. Running from it would violate Law 108; refusing is the stall the RC-4
                // drill measured. The certified anchor is the attribution — sync to it and catch
                // up, and never serve the stale fence. The sync fetches the certificate itself, so
                // the statement it verifies is the one it syncs from.
                log.warn(
                    source,
                    &format!(
                        "boot: the accepted fringe ({} block(s)) is not anchored by the fetched \
                         certificate; joining light and catching up",
                        repr.dag_set.len()
                    ),
                );
                light_join = true;
                needs_sync = true;
                pending_decision = Some(decision.clone());
            } else {
                let coordinate = if matches!(fringe_agreement.as_deref(), Some("mismatch")) {
                    BootCoordinate::FringeMismatch
                } else {
                    BootCoordinate::NoStoredCertificate
                };
                decision.write(false, None, Some(coordinate));
                return Err(format!(
                    "this node's DAG holds {} block(s) but no verified checkpoint certificate; the \
                     accepted state cannot be attributed, so the node refuses to run (a genesis \
                     anchor is only for a genesis-only DAG)",
                    repr.dag_set.len()
                ));
            }
        }
        // **A light join has accepted nothing yet**: its trace is written by the sync's outcome,
        // not here. Every attributable boot writes the decision now.
        if !light_join {
            decision.write(true, None, None);
        }
    }

    // **The one checkpoint sync** (join ladder, RC-4). An empty DAG and a pending recovery
    // enter it as they always have; so does a reconnect whose accepted fringe no fetched
    // certificate anchors. The node then runs from the certified anchor and never from the
    // stale fence — one sync body, one engine loop, one terminal signal.
    if needs_sync {
        if light_join {
            log.warn(
                source,
                "the accepted fringe is not anchored by any checkpoint certificate; joining light \
                 from the certified anchor and catching up to the fence",
            );
        } else {
            log.info(source, "Starting from bootstrap node, syncing LFS...");
        }
        phase.set_phase(crate::engine::node_phase::NodePhase::Syncing);
        let engine = Arc::new(tokio::sync::Mutex::new(
            NodeSyncing::new(
                transport.clone(),
                rp_conf.clone(),
                block_store.clone(),
                dag.clone(),
                approved_store.clone(),
                comm_util.clone(),
                log.clone(),
                validator_identity_opt.clone(),
                trim_state,
                importer,
            )
            .with_replay(RecoveryReplay {
                runtime: runtime_manager.clone(),
                shard_id: spec.shard_id.to_string(),
                min_phlo_price: spec.genesis_block_data.min_phlo_price,
                max_number_of_parents: spec.genesis_block_data.max_number_of_parents,
                expected_genesis: expected_genesis_hash,
                anchor: boot_anchor,
                checkpoint_source: checkpoint_source.clone(),
                checkpoint_store: Some(checkpoint_store.clone()),
            }),
        ));
        // **A named anchor replaces the fringe request** (C259). A peer with no finalised fringe answers
        // a `FinalizedFringeRequest` with **genesis** (`node_running.rs`), so a wiped joiner syncs to
        // block 0 and can never re-enter sync — which is the state a chain with frozen finality is in,
        // and the reason this switch exists. The anchor is the block the operator's reconciliation
        // computed: the deepest height a strict supermajority of stake agrees on.
        //
        // Nothing else about the sync changes. `request_blocks` walks from whatever hashes it is given
        // (`lfs_block_requester.rs`), so seeding it with an anchor rather than with a peer's fringe is
        // the same machinery with a different root — and `request_tuple_space` then pulls the state at
        // the anchor's post-state, exactly as it would for a fringe.
        // **Ask for the fringe anchored at the certified checkpoint** (sync/verification
        // separation). The certificate names the anchor and its post-state; an anchored request
        // returns exactly that fringe (the anchor's closure), so the statement the joiner verifies
        // and the history it walks are the same history by construction. Without a certificate the
        // ordinary request is used and the attempt fails closed later — there is no unsigned
        // fallback; the retry loop re-asks, which is what lets a just-started bootstrap certify.
        if boot_anchor.is_none() {
            if let Some(served_by) = checkpoint_source.as_ref() {
                match served_by.fetch_certificate().await {
                    Ok(certificate) => {
                        match crate::checkpoint::verify_genesis_rooted_certificate(
                            &certificate,
                            &runtime_manager.genesis_pos().bonds,
                        ) {
                            Ok(verified) if verified.checkpoint.shard_id == spec.shard_id.to_string() => {
                                match BlockHash::try_from_hex(&verified.checkpoint.anchor) {
                                    Ok(anchor) => {
                                        log.info(
                                            source,
                                            &format!(
                                                "Requesting the fringe anchored at the certified \
                                                 checkpoint {} (height {})",
                                                anchor.to_hex(),
                                                verified.checkpoint.anchor_height
                                            ),
                                        );
                                        // **Persist it before the engine uses it.** A spoke whose
                                        // collector never reaches quorum had nothing in the store, so
                                        // its next boot refused; the certificate the sync already
                                        // trusts is the one the store must re-verify then. A record
                                        // conflict is an equivocation at this anchor and is refused,
                                        // not adopted.
                                        if let rchain_block_storage::checkpoint_store::Recorded::Conflict {
                                            existing_digest,
                                        } = checkpoint_store
                                            .record(&verified.digest, &certificate)
                                            .await?
                                        {
                                            return Err(format!(
                                                "the served checkpoint certificate conflicts with \
                                                 an already recorded statement at its anchor \
                                                 (existing {})",
                                                existing_digest.to_hex()
                                            ));
                                        }
                                        if let rchain_block_storage::checkpoint_store::Adoption::Conflict {
                                            head_digest,
                                            incoming_digest,
                                        } = checkpoint_store
                                            .adopt(&verified.digest, &certificate, false)
                                            .await?
                                        {
                                            return Err(format!(
                                                "the served checkpoint certificate conflicts with \
                                                 the adopted head (head {:?}, incoming {})",
                                                head_digest.map(|digest| digest.to_hex()),
                                                incoming_digest.to_hex()
                                            ));
                                        }
                                        // **The same statement the anchor came from** goes with the
                                        // engine: the sync task verifies it rather than fetching a
                                        // newer one, so the signed statement and the served fringe
                                        // cannot be two different histories.
                                        engine
                                            .lock()
                                            .await
                                            .set_checkpoint_certificate(certificate.clone());
                                        boot_anchor = Some(anchor);
                                    }
                                    Err(e) => log.warn(
                                        source,
                                        &format!(
                                            "the served checkpoint names an unparseable anchor: {e}"
                                        ),
                                    ),
                                }
                            }
                            Ok(verified) => log.warn(
                                source,
                                &format!(
                                    "the served checkpoint names shard {:?}, not this node's {:?}",
                                    verified.checkpoint.shard_id, spec.shard_id
                                ),
                            ),
                            Err(e) => log.warn(
                                source,
                                &format!(
                                    "the served checkpoint certificate was refused ({e}); asking \
                                     for the ordinary fringe"
                                ),
                            ),
                        }
                    }
                    Err(e) => log.info(
                        source,
                        &format!(
                            "no checkpoint certificate is served yet ({e}); asking for the ordinary \
                             fringe — the sync will fail closed until one is"
                        ),
                    ),
                }
            }
        }

        let anchor = boot_anchor;
        // **The anchor is named *in the request*, not fetched and patched in afterwards** (C259a).
        // Seeding the sync from the anchor block alone left `ancestry` empty, which bypasses exactly the
        // #139 fix that makes a restored block replayable: no block below the anchor then carries the
        // fringe state the joiner cannot derive, the joiner falls back to deriving it, that derivation
        // needs a sidecar the LFS transfer does not send, and the node stalls **at** the anchor —
        // silently near the tip, and loudly on an older one (`validateBlockCheckpoint failed:
        // regenerated mergeable channels…`). The responder now builds the fringe *and its ancestry* from
        // the named block, so a recovery restore carries the same data the ordinary fringe path does.
        //
        // Nothing else about the sync changes. `request_blocks` walks from whatever hashes it is given
        // (`lfs_block_requester.rs`), so seeding it with an anchor rather than with a peer's fringe is
        // the same machinery with a different root — and `request_tuple_space` then pulls the state at
        // the anchor's post-state, exactly as it would for a fringe.
        if let Some(hash) = anchor {
            if rp_conf.bootstrap.is_none() {
                return Err(
                    "--sync-anchor needs a bootstrap to ask for the anchor's fringe, and this node \
                     has none configured"
                        .to_string(),
                );
            }
            log.info(
                source,
                &format!(
                    "Syncing to the operator-named anchor {} rather than to a fringe a peer offers: \
                     with finality frozen no peer has one, and the answer to an ordinary fringe request \
                     would be the genesis block (C259)",
                    hash.to_hex()
                ),
            );
        }
        // With no anchor this *is* the ordinary request; with one, the same request names the root.
        let received = { engine.lock().await.initial_fringe_received_handle() };
        let request = comm_util.request_initial_fringe(trim_state, anchor, received);
        tokio::pin!(request);

        // Handle packets concurrently with the syncing-finished signal, and with the **terminal**
        // one (AUDIT C181, #125). `finished` is the successful exit — the state was restored, go on
        // to `NodeRunning`. `terminal` is the other one: the sync retries are spent and this node
        // cannot reach the approved state, so it stops serving rather than sitting in `NodeSyncing`
        // for good, which is the state no rule left. Signalling `finished` here instead would move
        // the node into `NodeRunning` on a DAG it never populated, which is what C68 exists to
        // prevent — the two facts are different and get different signals.
        let finished = { engine.lock().await.finished_handle() };
        let terminal = { engine.lock().await.terminal_handle() };
        let accepted_cell = { engine.lock().await.accepted_state_handle() };
        let handle_loop = async {
            while let Some(pm) = packet_rx.recv().await {
                let mut guard = engine.lock().await;
                if let Err(err) = guard.handle(&pm.peer, &pm.message).await {
                    log.warn(
                        source,
                        &format!("Error handling message from {}: {err}", pm.peer),
                    );
                }
            }
        };
        tokio::pin!(handle_loop);
        let mut awaiting_initial_fringe = true;
        loop {
            tokio::select! {
                _ = &mut handle_loop => break,
                _ = finished.notified() => break,
                result = &mut request, if awaiting_initial_fringe => {
                    result?;
                    awaiting_initial_fringe = false;
                }
                _ = terminal.notified() => {
                // **The reason travels with the sentence** (C271/C268). "The retries are spent" is
                // only half the fact, and without *why* the operator's one error line said the node
                // was giving up and nothing about what it could not restore. The failure is read from
                // the same static the status surface carries, so the log line and `/api/v1/status`
                // agree; the fallback keeps the old wording if the reading is somehow absent rather
                // than printing `None`.
                let reason = crate::engine::node_syncing::sync_state()
                    .and_then(|state| state.last_failure);
                let message = match reason {
                    Some(reason) => format!(
                        "LFS state sync is terminal: the approved state could not be restored and the \
                         retries are spent: {reason}, so this node is stopping rather than serving a \
                         chain it never synced"
                    ),
                    None => "LFS state sync is terminal: the approved state could not be restored and \
                             the retries are spent, so this node is stopping rather than serving a \
                             chain it never synced"
                        .to_string(),
                };
                    phase.set_phase(crate::engine::node_phase::NodePhase::Blocked(
                        "LFS state sync is terminal".to_string(),
                    ));
                    // **The decision trace is written with the outcome**, so a light join that
                    // could not restore the approved state is an unsafe point, not a model gap.
                    if let Some(decision) = pending_decision.take() {
                        decision.write(
                            false,
                            Some("light-join-failed"),
                            Some(BootCoordinate::SyncTerminal),
                        );
                    }
                    return Err(message);
                }
            }
        }
        // **A successful sync must have produced an anchor.** `finished` carries the signal; the
        // accepted state is the payload. A signal without one is refused rather than running on the
        // DAG the attempt happened to leave (Law 108).
        accepted_state = accepted_cell.lock().await.clone();
        if accepted_state.is_none() {
            return Err(
                "LFS sync signalled success without an accepted state; refusing to run".to_string(),
            );
        }
        // **A light join succeeded**: the accepted state is the certified anchor the sync restored,
        // so the decision is safe and the stale fence was never served.
        if let Some(decision) = pending_decision.take() {
            decision.write(true, Some("light-join"), None);
        }
    }

    // **The derived-index audit, at every boot** (B39, HAZOP F-U17-11). It is independent of the reset
    // marker: a store can carry stale rows from a crash on an older build, or from a rewind whose empty
    // metadata drop skipped the cleanup. The repair is idempotent and derives the stale rows from the
    // surviving block set. A failure is logged and the node runs — the rows make the proposer skip a
    // pooled deploy (its replay guard reads the index), which is a defect to repair on the next boot,
    // not a reason to refuse to serve a chain.
    let audit_started = std::time::Instant::now();
    match dag.repair_derived_indexes().await {
        Ok((0, 0)) => {}
        Ok((deploy_rows, deployer_rows)) => log.warn(
            source,
            &format!(
                "boot index audit repaired {deploy_rows} deploy-index and {deployer_rows} \
                 deployer-index row(s) that named a block this DAG does not hold (B39, F-U17-11; {} ms)",
                audit_started.elapsed().as_millis()
            ),
        ),
        Err(e) => log.warn(
            source,
            &format!(
                "boot index audit could not run: {e}; stale derived-index rows may make the proposer \
                 skip a pooled deploy until it succeeds"
            ),
        ),
    }

    // **Publish the accepted anchor's root** (Law 108; law 80, B40). The running root is the
    // anchor's root by construction. A boot with no anchor, or an anchor whose root this store does
    // not know, refuses to run — there is no heuristic fallback to a DAG tip or an approved fringe.
    let accepted = accepted_state.take().ok_or_else(|| {
        "this node has no trust anchor (no verified checkpoint certificate and no genesis-only DAG), \
         so it refuses to run"
            .to_string()
    })?;
    // **Install the runtime's admissible pre-state window** (review R2) before any block can be
    // accepted: the anchor root, the certified window, and the roots this node already derived above
    // the anchor. The state store's contents are never consulted for permission.
    let mut runtime_window = crate::engine::anchor::AcceptedWindow::from_accepted(&accepted);
    seed_derived_roots(dag.as_ref(), accepted.anchor(), &mut runtime_window).await?;
    *accepted_window.write().await = Some(runtime_window);
    // **The pin is enforced before publication** (review R5): a boot that would refuse must not have
    // moved `CURRENT_ROOT` first.
    if let Some(expected) = expected_genesis_hash {
        check_expected_genesis(dag.as_ref(), &expected).await?;
    }
    match runtime_manager.publish_accepted_root(accepted.root()).await {
        Ok(true) => log.info(source, "published CURRENT_ROOT from the accepted anchor"),
        Ok(false) => {
            return Err(format!(
                "the accepted anchor names a root this store does not know ({}); refusing to run",
                accepted.root().to_hex()
            ))
        }
        Err(e) => return Err(format!("could not publish the accepted root: {e}")),
    }

    // The synced root is content-addressed, but its params must also be readable by this binary
    // and agree with this node's admission/proposal configuration before it enters Running.
    // Do this on reconnect and local genesis too, so a restart cannot bypass the restore guard.
    check_running_validation_bounds(
        dag.as_ref(),
        &block_store,
        &approved_store,
        runtime_manager.as_ref(),
        spec.genesis_block_data.min_phlo_price,
        spec.genesis_block_data.max_number_of_parents,
    )
    .await?;
    // The restored allocation gets the same treatment: the imported leaf must be internally
    // consistent, and a joiner that made a local allocation claim must match it. A joiner with no
    // claim (the normal public bootstrap) trusts the chain.
    check_running_dev_vesting(
        dag.as_ref(),
        &block_store,
        &approved_store,
        runtime_manager.as_ref(),
        runtime_manager.genesis_pos().dev_vesting.clone(),
    )
    .await?;

    // **The catch-up window and the driver that walks it** (C259). A node restored at an anchor below
    // its peers' tip cannot ingest the gap through the hash-keyed pull: the walk runs downward from a
    // peer's tip, each block justifies ones inside the gap, and the receiver's pending set saturates
    // (measured: 173 drops, one block validated, frozen 121 against a master's 577). The window narrows
    // the ingest to a couple of windows' worth while the driver walks outward asking for heights;
    // released — by the driver's every exit path, including its first empty answer — the ingest is
    // exactly what it was before, so a node that never catches up is unaffected.
    let catchup = Arc::new(CatchupWindow::new(catchup::WINDOW_HEIGHTS));

    // **The cell the validator path uses to ask for a reset** (F-U5-01's acting half, #320). Installed
    // before the running phase, because the detection happens deep in the validator path — which holds
    // no transport, no block store and no runtime — and the reset is performed *here*, where all three
    // are in scope. The request and the arms it refuses are `interpreter_util`'s.
    let reset_wake = Arc::new(tokio::sync::Notify::new());
    // **This shard's lane** (§107's D4). The cells are process-wide while a node may be a member of
    // several shards, so the key is what keeps a request raised by one shard from reaching another's
    // driver — and once a failed reset stops the node, that misdelivery would be a whole-node kill.
    // `ShardId::to_string()` is the value both halves derive, this side from the `ShardSpec` and the
    // detector's from the same id.
    let shard_lane = spec.shard_id.to_string();
    crate::interpreter_util::install_reset_waker(shard_lane.clone(), reset_wake.clone());

    // The catch-up walk's door. The engine funnels a peer's `BlockRangeRequest` answers down it and the
    // walk owns the receiving end, so a *second* walk needs a second channel — which is why this is a
    // cell the engine reads per answer rather than a sender it owns.
    let block_range_door: crate::engine::node_running::BlockRangeDoor =
        Arc::new(tokio::sync::Mutex::new(tokio::sync::mpsc::channel(4).0));

    // **The launch decides the phase before the audit writes it** (Laws 121/123, RC-4 item A). The
    // audit's `Running` write used to precede this decision, leaving a multi-await window in which a
    // propose was admitted on a view the launch was about to reject. A node that restored through
    // the sync/join path is behind by construction — its restored view is the anchor it adopted, not
    // the network's tip — so it is not served until a peer probe confirms the window. Every other
    // boot trusts its restored view; the supervisor observes it from then on and re-enters catch-up
    // if the view leaves the window (Law 123).
    let walk_wake = Arc::new(tokio::sync::Notify::new());
    let (decided_phase, catchup_bonds) = {
        let bonds = runtime_manager
            .compute_bonds(&rchain_models::block::state_hash::StateHash::from_slice(
                accepted.root().as_bytes(),
            ))
            .await?;
        let own = catchup::validated_frontier_of(dag.as_ref()).await;
        catchup.set_own_tip(own);
        let (_, supported) = catchup::view(
            dag.get_representation()
                .await
                .dag_message_state
                .latest_msgs
                .values()
                .map(|message| (message.sender.clone(), message.height)),
            &bonds,
        );
        let supported = i64::from(supported);
        let decided = if needs_sync {
            log.warn(
                source,
                &format!(
                    "this node restored through the sync path and is not served until a peer probe \
                     confirms the catch-up window: own validated tip {own}, quorum-supported \
                     {supported}"
                ),
            );
            crate::engine::node_phase::NodePhase::CatchingUp {
                supported,
                own,
                peer_tip: own,
            }
        } else {
            crate::engine::node_phase::NodePhase::Running
        };
        (decided, bonds)
    };
    let audit = crate::block_disposition::startup_audit_then_running(
        &phase,
        decided_phase,
        &block_disposition,
        &block_store,
        &dag,
        &to_processor,
        crate::block_disposition::STARTUP_AUDIT_DRAIN_TIMEOUT,
        &log,
    )
    .await;
    log.info(
        source,
        &format!(
            "start-up disposition audit: {} pre-ledger body/bodies adopted, {} re-offered, {} \
             skipped for missing parents, {} still pending when the drain closed{}",
            audit.scan.as_ref().map(|scan| scan.adopted).unwrap_or(0),
            audit.reoffer.reoffered,
            audit.reoffer.skipped_missing_parents,
            audit.drain.still_pending,
            if audit.drain.timed_out {
                " (bounded window)"
            } else {
                ""
            }
        ),
    );
    // **The continuous catch-up supervisor** (Laws 121/123; HAZOP J3/J4). It is the shard's only
    // phase observer after launch: it samples the node's own validated tip, probes a connected peer
    // for its frontier (a bounded `BlockRange` answer), and re-enters `CatchingUp` on a confirmed
    // stale view. A walk request wakes the running loop, which owns the walk so there is at most
    // one. The boot flag makes the first probe load-bearing for a joined node.
    spawn_catchup_supervisor(
        phase.clone(),
        dag.clone(),
        catchup_bonds,
        catchup.clone(),
        comm_util.clone(),
        rp_conf.clone(),
        connections.clone(),
        log.clone(),
        walk_wake.clone(),
        needs_sync,
    );

    // **The consumer pool** (max-message-consumers). `NodeRunning::handle` takes `&self`, so the
    // engine is shared behind an `Arc` and each packet is handled by its own task under a permit.
    // The permit is acquired *before* the spawn, which is the backpressure: a full pool parks the
    // receive loop instead of building an unbounded task list. A packet refused by the pool would
    // be a message the peer must resend anyway; parking the loop is the same delay with no drop.
    // **The body backfill** (sync/verification separation). A certified joiner holds headers only;
    // this task closes the gap in the background, lowest height first. Off is the light-node mode.
    let backfill_tx = if backfill_bodies {
        let (tx, rx) = tokio::sync::mpsc::channel(50);
        crate::engine::backfill::spawn(
            dag.clone(),
            block_store.clone(),
            checkpoint_store.clone(),
            comm_util.clone(),
            spec.shard_id.to_string(),
            log.clone(),
            rx,
        );
        Some(tx)
    } else {
        None
    };
    let engine = std::sync::Arc::new(NodeRunning::new(
        transport.clone(),
        rp_conf.clone(),
        block_store.clone(),
        dag.clone(),
        block_retriever.clone(),
        log.clone(),
        validator_identity_opt.clone(),
        // The claims cell is fed by the engine at signature-verified receipt (Law 124); the
        // proposer holds the same clone.
        received_claims,
        incoming_blocks,
        exporter,
        disable_state_exporter,
        catchup.clone(),
        block_range_door.clone(),
        backfill_tx,
    ));
    let consumer_slots =
        std::sync::Arc::new(tokio::sync::Semaphore::new(max_message_consumers.max(1)));
    // **A signature the DAG forgot is reconciled from the network** (Law 122, RC-4 HAZOP J8). The
    // durable record names the block that carried the validator's last signed sequence; a rewind
    // may have dropped it. Asking the peers for exactly that block either re-adopts it (the
    // snapshot then reaches the record and the proposer proceeds) or establishes that the network
    // dropped that branch — in which case the record protects nothing and is retired, rather than
    // halting the validator for ever.
    if let Some(identity) = validator_identity_opt.as_ref() {
        spawn_own_record_reconciler(
            phase.clone(),
            dag.clone(),
            block_retriever.clone(),
            rchain_models::validator::Validator::from_slice(identity.public_key.bytes()),
            log.clone(),
        );
    }
    log.info(source, "Making a transition to Running state.");

    // **The anchor this running phase walks to**: the operator's at boot, or the one a reset rewound to.
    let mut phase_anchor = boot_anchor;

    wait_for_first_connection(&connections, log.as_ref()).await;
    comm_util.send_fork_choice_tip_request().await;

    loop {
        start_catchup_if_anchored(
            &mut phase_anchor,
            &block_range_door,
            &catchup,
            &transport,
            &rp_conf,
            &connections,
            &dag,
            &self_replay_resume,
            &log,
            source,
        )
        .await;

        /// Why the running loop woke up. The stream ending is the node shutting down; the reset is a
        /// state this node decided it needs; a walk request is the catch-up supervisor asking for a
        /// fresh walk (Law 123). Only the last two loop.
        enum RunningWake {
            Shutdown,
            Reset,
            Walk,
        }
        // **Three exits, not two** (#320), plus the walk request. The stream ending is the node
        // shutting down; the reset and the walk both return to the top.
        let wake = tokio::select! {
            _ = async {
                let mut tip_refresh = tokio::time::interval(RUNNING_TIP_REFRESH_INTERVAL);
                tip_refresh.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
                // The startup request above has already run. Avoid an extra
                // round at time zero, then reconcile a peer's tip every 30s.
                tip_refresh.tick().await;
                loop {
                    tokio::select! {
                        packet = packet_rx.recv() => {
                            let Some(pm) = packet else { break; };
                            // **Two lanes** (the Scala consumer pool, ported). The expensive
                            // read/answer kinds run in the pool; block ingress, fringe traffic and
                            // the range answers the catch-up walk depends on stay on this loop, in
                            // arrival order. A read request that finds the pool full is dropped
                            // rather than parking the loop — its requester retries, and the
                            // ordering-sensitive lane must keep moving.
                            let (pooled, kind) = match &pm.message {
                                CasperMessage::StoreItemsMessageRequest(_) => (true, "store-items request"),
                                CasperMessage::BlockRequest(_) => (true, "block request"),
                                CasperMessage::HasBlockRequest(_) => (true, "has-block request"),
                                CasperMessage::ForkChoiceTipRequest(_) => (true, "fork-choice-tip request"),
                                _ => (false, "message"),
                            };
                            if pooled {
                                match consumer_slots.clone().try_acquire_owned() {
                                    Ok(permit) => {
                                        let engine = engine.clone();
                                        tokio::spawn(async move {
                                            engine.handle(&pm.peer, &pm.message).await;
                                            drop(permit);
                                        });
                                    }
                                    Err(_) => {
                                        log.warn(
                                            source,
                                            &format!(
                                                "Inbound consumer pool at capacity ({}); a {} from {} \
                                                 was dropped and its requester will retry",
                                                max_message_consumers,
                                                kind,
                                                pm.peer,
                                            ),
                                        );
                                    }
                                }
                            } else {
                                engine.handle(&pm.peer, &pm.message).await;
                            }
                        }
                        _ = tip_refresh.tick() => {
                            // A connected-but-previously-unreachable validator
                            // can miss every hash announced during the partition.
                            // Requesting latest heads makes ordinary block
                            // retrieval discover the ancestry it did not hear.
                            comm_util.send_fork_choice_tip_request().await;
                        }
                    }
                }
            } => RunningWake::Shutdown,
            _ = reset_wake.notified() => RunningWake::Reset,
            _ = walk_wake.notified() => RunningWake::Walk,
        };
        match wake {
            RunningWake::Shutdown => return Ok(()),
            RunningWake::Walk => {
                // One walk at a time: a reset's walk or a previous request may still be running.
                if catchup.is_active() {
                    log.info(
                        source,
                        "a catch-up walk is already active; the new request is coalesced",
                    );
                } else {
                    match catch_up_walk_peer(&rp_conf, &connections).await {
                        Some(peer) => {
                            start_walk(
                                peer,
                                &block_range_door,
                                &catchup,
                                &transport,
                                &rp_conf,
                                &connections,
                                &dag,
                                &self_replay_resume,
                                &log,
                            )
                            .await;
                        }
                        None => log.warn(
                            source,
                            "a catch-up walk was requested with no peer to walk against",
                        ),
                    }
                }
                continue;
            }
            RunningWake::Reset => {}
        }

        // The arm's body, extracted: what a running node does when the waker fires belongs in
        // `engine::reset` with the rest of the reset, and — the reason it is extracted at all — it is
        // then testable without a transport, an importer or a spec, which an `apply`-level test would
        // need a large fixture for while testing five lines of `select!`.
        match crate::engine::reset::act_on_reset_request(
            &shard_lane,
            self_reset,
            self_replay_reset,
            &dag,
            &block_store,
            &runtime_manager,
            &log,
            source,
        )
        .await?
        {
            // Nothing pending (a spurious wake), or the switch is off and the node has said so.
            None => continue,
            Some(request) => {
                phase_anchor = Some(request.anchor);
                log.warn(
                    source,
                    &format!(
                        "reset complete: rewound to {} (height {}), the runtime is at that state and the \
                         catch-up walk is restarting from it — the blocks above are re-requested from \
                         {} (#320)",
                        request.anchor.to_hex(),
                        i64::from(request.anchor_height),
                        rp_conf
                            .bootstrap
                            .as_ref()
                            .map(|p| p.endpoint.host.clone())
                            .unwrap_or_else(|| "no peer".to_string()),
                    ),
                );
            }
        }
    }
}

/// Check the restored/startup params before admission and proposal enter the running phase.
pub async fn check_running_validation_bounds(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    approved_store: &ApprovedStore,
    runtime: &RuntimeManager,
    min_phlo_price: i64,
    max_number_of_parents: i32,
) -> Result<(), String> {
    let approved = get_approved_block(approved_store)
        .await?
        .ok_or_else(|| "cannot enter Running without an approved state".to_string())?;
    let params_root = restored_native_state_root(dag, block_store, &approved).await?;
    runtime
        .check_configured_validation_bounds(&params_root, min_phlo_price, max_number_of_parents)
        .await
}

/// **The state whose native leaves the restore guard reads.**
///
/// The approved fringe's `state_hash` is a *fringe* state, not a block's post-state. On a snapshot
/// restore the native leaves (the committed PoS params) live in a block's post-state, and reading the
/// fringe root asks the history for a leaf that was never written there: a good restore is refused
/// with "PoS params leaf not found in committed state".
///
/// **Why the first hash at the highest height is safe.** The committed params are immutable for the
/// life of the chain, so every validated block at the newest height carries the same params in its
/// post-state. Which sibling is chosen therefore cannot change the answer.
async fn restored_native_state_root(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    approved: &FinalizedFringe,
) -> Result<StateHash, String> {
    if approved.hashes.is_empty() {
        // The genesis fringe names the empty pre-state, not the installed PoS descriptors.
        return genesis_post_state_hash(dag, block_store)
            .await?
            .ok_or_else(|| "cannot locate genesis params after restore".to_string());
    }
    let repr = dag.get_representation().await;
    if let Some((_, hashes)) = repr.height_map.iter().next_back() {
        let hash = hashes.first().ok_or_else(|| {
            "restored DAG has a newest height without any block hashes".to_string()
        })?;
        // **The metadata is the record, and a metadata-only sync has no body** (sync/verification
        // separation). A record written before the field existed carries the zero root; only then
        // is the body the sole copy, and a node that holds neither refuses by name.
        return post_state_of(dag, block_store, hash).await;
    }
    // Only a synthetic, empty DAG has no block post-state to inspect.
    // Never silently substitute a fringe root when the DAG names a missing block.
    Ok(approved.state_hash)
}

/// Refuse to enter Running on a different genesis, including when restarting a populated DAG.
async fn check_expected_genesis(
    dag: &dyn BlockDagStorage,
    expected: &BlockHash,
) -> Result<(), String> {
    let repr = dag.get_representation().await;
    check_genesis_height_map(repr.height_map.as_ref(), expected)
}

/// The identity pin is a claim about the *unique block at height zero*, not about
/// whichever block happens to appear first in an incomplete or forked DAG index.
fn check_genesis_height_map(
    heights: &BTreeMap<BlockHeight, BTreeSet<BlockHash>>,
    expected: &BlockHash,
) -> Result<(), String> {
    let roots = heights.get(&BlockHeight::zero()).ok_or_else(|| {
        "expected genesis hash is pinned but the restored DAG has no height-zero genesis; refusing to enter Running".to_string()
    })?;
    if roots.len() != 1 {
        return Err(format!(
            "expected one genesis at height zero, found {}; refusing to enter Running",
            roots.len()
        ));
    }
    let actual = roots.first().ok_or_else(|| {
        "expected genesis hash is pinned but height zero is empty; refusing to enter Running"
            .to_string()
    })?;
    compare_genesis_hash(expected, actual)
}

fn compare_genesis_hash(expected: &BlockHash, actual: &BlockHash) -> Result<(), String> {
    if actual != expected {
        return Err(format!(
            "restored genesis {} differs from pinned genesis {}; refusing to enter Running",
            actual.to_hex(),
            expected.to_hex()
        ));
    }
    Ok(())
}

/// The genesis block's post-state hash, from the restored DAG. `None` when the DAG has no genesis
/// (a synthetic approved state in a guard unit test).
async fn genesis_post_state_hash(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
) -> Result<Option<StateHash>, String> {
    let repr = dag.get_representation().await;
    let Some(genesis_hash) = repr
        .height_map
        .first_key_value()
        .and_then(|(_, hashes)| hashes.first())
    else {
        return Ok(None);
    };
    post_state_of(dag, block_store, genesis_hash)
        .await
        .map(Some)
}

/// **A block's post-state, from the metadata when it has one.** The certified sync path holds no
/// body for the history it accepted; the record carries the root, and only a pre-field record falls
/// back to the body. A node that holds neither says so rather than substituting a fringe root.
async fn post_state_of(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    hash: &BlockHash,
) -> Result<StateHash, String> {
    if let Some(meta) = dag.lookup(hash).await? {
        if meta.post_state_hash != StateHash::new([0u8; 32]) {
            return Ok(meta.post_state_hash);
        }
    }
    block_store
        .get(&[*hash])
        .await?
        .into_iter()
        .next()
        .flatten()
        .map(|block| block.post_state_hash)
        .ok_or_else(|| {
            format!(
                "block {} has neither a recorded post-state nor a body, so the restore guard \
                 cannot read it",
                hash.to_hex()
            )
        })
}

/// Check the restored developer allocation before admission and proposal enter the running phase.
///
/// **Enforce when present, trust when absent.** A joiner that made a local allocation claim — bonds
/// and wallets files present, and a non-empty `dev-tax-address` — must match the imported genesis.
/// A joiner with no claim carries `None`, which means *no claim*, not *a claim of no allocation*: the
/// normal public-testnet bootstrap restores a chain whose genesis predates the joiner's config, and
/// must not be refused for it.
///
/// **The imported leaf's own schedule is always checked.** At the genesis post-state nothing has
/// vested (`unreleased == allocation`); at any later state the unreleased amount cannot exceed the
/// allocation. A larger one would make `release_dev_tax` compute a negative already-released amount
/// and over-credit the recipient — a silent mint at the next boundary.
pub async fn check_running_dev_vesting(
    dag: &dyn BlockDagStorage,
    block_store: &BlockStore,
    approved_store: &ApprovedStore,
    runtime: &RuntimeManager,
    local: Option<(String, NonNegI64)>,
) -> Result<(), String> {
    let approved = get_approved_block(approved_store)
        .await?
        .ok_or_else(|| "cannot enter Running without an approved state".to_string())?;
    let genesis_root = genesis_post_state_hash(dag, block_store).await?;
    // A genesis-only joiner carries `hashes: [genesis_hash]`; the hash comparison, not the fringe
    // shape, is what identifies the genesis state.
    let restored_root = restored_native_state_root(dag, block_store, &approved).await?;
    let at_genesis = genesis_root == Some(restored_root);
    let imported = runtime.committed_dev_vesting(&restored_root).await?;

    if let Some((local_address, local_allocation)) = local {
        match &imported {
            Some(leaf) if leaf.address == local_address && leaf.allocation == local_allocation => {}
            Some(leaf) => {
                return Err(format!(
                    "local developer allocation ({local_address}, {local_allocation:?}) does not \
                     match the restored genesis ({}, {:?}) at state {}; refusing to enter Running",
                    leaf.address,
                    leaf.allocation,
                    hex(restored_root)
                ));
            }
            None => {
                return Err(format!(
                    "local developer allocation ({local_address}, {local_allocation:?}) but the \
                     restored genesis at state {} has none; refusing to enter Running",
                    hex(restored_root)
                ));
            }
        }
    }

    if let Some(leaf) = &imported {
        if at_genesis {
            if leaf.unreleased != leaf.allocation {
                return Err(format!(
                    "restored genesis allocation at state {} has unreleased {:?} of {:?}; refusing \
                     to enter Running",
                    hex(restored_root),
                    leaf.unreleased,
                    leaf.allocation
                ));
            }
        } else if leaf.unreleased > leaf.allocation {
            return Err(format!(
                "restored allocation at state {} has unreleased {:?} of {:?}; refusing to enter \
                 Running",
                hex(restored_root),
                leaf.unreleased,
                leaf.allocation
            ));
        }
    }
    Ok(())
}

fn hex(hash: StateHash) -> String {
    hash.as_bytes()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// How often the catch-up supervisor samples the node's view.
const CATCH_UP_TICK: Duration = Duration::from_secs(2);

/// How often the supervisor probes a peer's frontier. The first probe of a joined boot is sent on
/// the first tick, and every tick until an answer arrives (bounded by the boot wait).
const CATCH_UP_PROBE_TICKS: u32 = 5;

/// How many ticks a joined boot waits for its first probe answer before running on the restored
/// view. Ten seconds: long enough for a connection and a range round trip, short enough that a node
/// whose peer is unreachable does not sit in `CatchingUp` for the harness's whole window.
const CATCH_UP_BOOT_PROBE_TICKS: u32 = 5;

/// How many connected peers a probe round asks (the bootstrap first).
const CATCH_UP_PROBE_PEERS: usize = 3;

/// **The continuous catch-up supervisor** (Laws 121/123; RC-4 HAZOP J3/J4).
///
/// The launch decides the boot phase; this task is the shard's only phase observer afterwards. On
/// every tick it:
///
/// * samples the node's **own validated tip** (the highest latest message it has validated) and
///   publishes it on the catch-up cell;
/// * probes a connected peer, preferring the bootstrap, with a one-height `BlockRangeRequest`; the
///   answer's `tip` is the peer's frontier (`node_running.rs` observes it before the door);
/// * applies [`catchup::supervise_phase`]: a confirmed stale view re-enters `CatchingUp`, a current
///   view returns to `Running`, and a transition into catch-up wakes the running loop to start a
///   walk;
/// * fails closed to `Blocked` after [`catchup::CATCH_UP_STALL_TICKS`] without the node's own tip
///   rising. That is the safe fallback: a node that cannot close the gap stops serving and names
///   the coordinates, rather than reading `running`/ready while frozen.
///
/// It never overwrites a phase another writer moved (`Blocked`, `Syncing`, shutdown).
#[allow(clippy::too_many_arguments)]
fn spawn_catchup_supervisor(
    phase: crate::engine::node_phase::NodePhaseCell,
    dag: Arc<dyn BlockDagStorage>,
    bonds: BTreeMap<rchain_models::validator::Validator, NonNegI64>,
    window: Arc<CatchupWindow>,
    comm_util: Arc<CommUtil>,
    rp_conf: RPConf,
    connections: ConnectionsCell,
    log: Arc<dyn Log>,
    walk_wake: Arc<tokio::sync::Notify>,
    await_first_probe: bool,
) {
    tokio::spawn(async move {
        use crate::engine::node_phase::NodePhase;
        let source = LogSource::new("casper.engine.NodeLaunch");
        let mut stale_ticks: u32 = 0;
        let mut stall_ticks: u32 = 0;
        let mut last_own = i64::MIN;
        let mut probe_ticks: u32 = 0;
        let mut boot_probe_ticks: u32 = 0;
        let mut boot_wait_expired = false;
        let mut tick = tokio::time::interval(CATCH_UP_TICK);
        tick.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        loop {
            tick.tick().await;
            let current = phase.phase();
            match current {
                NodePhase::Starting | NodePhase::Syncing | NodePhase::Blocked(_) => return,
                NodePhase::Running | NodePhase::CatchingUp { .. } => {}
            }

            let own = catchup::validated_frontier_of(dag.as_ref()).await;
            window.set_own_tip(own);
            if own > last_own {
                last_own = own;
                stall_ticks = 0;
            } else {
                stall_ticks = stall_ticks.saturating_add(1);
            }
            let (_, supported) = catchup::view(
                dag.get_representation()
                    .await
                    .dag_message_state
                    .latest_msgs
                    .values()
                    .map(|message| (message.sender.clone(), message.height)),
                &bonds,
            );
            let supported = i64::from(supported);

            // **Probe.** A walk holds the door, so a probe answer would be mistaken for a window;
            // probe only while no walk is active. The boot probe is sent every tick until an answer
            // arrives; afterwards the interval is `CATCH_UP_PROBE_TICKS`.
            probe_ticks = probe_ticks.saturating_add(1);
            let boot_waiting = await_first_probe
                && !boot_wait_expired
                && window.probe_answers() == 0
                && window.peer_tip() < 0;
            if !window.is_active() && (probe_ticks >= CATCH_UP_PROBE_TICKS || boot_waiting) {
                probe_ticks = 0;
                for peer in catch_up_probe_peers(&rp_conf, &connections).await {
                    comm_util
                        .request_block_range(
                            &peer,
                            &BlockRangeRequest {
                                from: own.saturating_add(1),
                                to: own.saturating_add(1),
                            },
                        )
                        .await;
                }
            }

            // A peer at or behind this node says nothing about a gap; `peer_tip.max(own)` keeps the
            // comparison total before the first answer.
            let peer_tip = window.peer_tip().max(own);
            let boot_pending = await_first_probe
                && !boot_wait_expired
                && window.probe_answers() == 0
                && matches!(current, NodePhase::CatchingUp { .. })
                && boot_probe_ticks < CATCH_UP_BOOT_PROBE_TICKS;
            if boot_pending {
                boot_probe_ticks = boot_probe_ticks.saturating_add(1);
            }
            if await_first_probe
                && !boot_wait_expired
                && window.probe_answers() == 0
                && boot_probe_ticks >= CATCH_UP_BOOT_PROBE_TICKS
            {
                // The wait is over and nobody answered: run on the restored view, name the absence,
                // and keep probing. One expiry, not one per cycle.
                boot_wait_expired = true;
                log.warn(
                    source,
                    &format!(
                        "no peer answered the catch-up probe within {CATCH_UP_BOOT_PROBE_TICKS} \
                         ticks; running on the restored view (own {own}) and continuing to probe"
                    ),
                );
            }

            let stale = !catchup::within_window_i64(own, peer_tip);
            if stale {
                stale_ticks = stale_ticks.saturating_add(1);
            } else {
                stale_ticks = 0;
            }
            let next = if boot_pending {
                current.clone()
            } else {
                catchup::supervise_phase(&current, supported, own, peer_tip, stale_ticks)
            };
            if next != current {
                match &next {
                    NodePhase::CatchingUp { .. } => {
                        log.warn(
                            source,
                            &format!(
                                "catch-up re-entered: own validated tip {own}, peer tip \
                                 {peer_tip}, quorum-supported {supported} (window {})",
                                rchain_block_storage::dag::liveness::LIVENESS_WINDOW
                            ),
                        );
                        stall_ticks = 0;
                        walk_wake.notify_one();
                    }
                    NodePhase::Running => log.info(
                        source,
                        &format!(
                            "catch-up complete: own validated tip {own}, peer tip {peer_tip}; the \
                             shard is serving again"
                        ),
                    ),
                    _ => {}
                }
                phase.set_phase(next.clone());
            }

            // A walk that ended without closing the gap is retried every few ticks, so a single
            // silent peer or a lost window is not the end of the catch-up.
            if matches!(next, NodePhase::CatchingUp { .. })
                && !window.is_active()
                && stale
                && stall_ticks > 0
                && stall_ticks % CATCH_UP_PROBE_TICKS == 0
            {
                walk_wake.notify_one();
            }

            if matches!(next, NodePhase::CatchingUp { .. })
                && stall_ticks > catchup::CATCH_UP_STALL_TICKS
            {
                let reason = format!(
                    "catch-up stalled: own validated tip {own} against peer tip {peer_tip} for \
                     {stall_ticks} ticks; a node that cannot close the gap stops serving rather \
                     than reporting `running`"
                );
                log.error(source, &reason);
                phase.set_phase(NodePhase::Blocked(reason));
                return;
            }
        }
    });
}

/// The peers a probe round asks: the bootstrap first, then up to [`CATCH_UP_PROBE_PEERS`]-1
/// connected peers, deduplicated by endpoint.
async fn catch_up_probe_peers(rp_conf: &RPConf, connections: &ConnectionsCell) -> Vec<PeerNode> {
    let mut peers: Vec<PeerNode> = Vec::new();
    if let Some(bootstrap) = rp_conf.bootstrap.as_ref() {
        peers.push(bootstrap.clone());
    }
    for peer in connections.read().await.iter() {
        if peers.len() >= CATCH_UP_PROBE_PEERS {
            break;
        }
        if !peers.iter().any(|known| known.endpoint == peer.endpoint) {
            peers.push(peer.clone());
        }
    }
    peers
}

/// The peer a continuous walk runs against: the bootstrap, or the first connection.
async fn catch_up_walk_peer(rp_conf: &RPConf, connections: &ConnectionsCell) -> Option<PeerNode> {
    if let Some(bootstrap) = rp_conf.bootstrap.clone() {
        return Some(bootstrap);
    }
    connections.read().await.first().cloned()
}

/// How often the own-record reconciler asks the peers for the block it signed.
const OWN_RECORD_TICK: Duration = Duration::from_secs(2);

/// **How many asks before the record is retired.** At 2 s an ask, this is a minute of the peers'
/// answers — long enough for a catch-up walk and a gossip round to deliver a block any peer holds,
/// short enough that a validator whose branch the network dropped resumes instead of halting.
const OWN_RECORD_ATTEMPTS: u32 = 30;

/// **Reconcile the durable own-sequence record with the network** (Law 122; RC-4 HAZOP J8).
///
/// The record names the block that carried this validator's last signed sequence. After a rewind
/// that block may be gone locally. Three outcomes, all bounded and named:
///
/// * the DAG already holds it (the catch-up walk re-adopted it) → nothing to do;
/// * a peer serves it → the DAG adopts it, the round snapshot reaches the record, and the proposer
///   resumes above it — this is the case where re-signing would have been a slashable duplicate;
/// * no answering peer serves it → the signature is on a branch the network dropped. The record
///   protects nothing; it is **retired** and the proposer derives from the snapshot. The residual
///   risk is a peer that holds the block but never answered (disconnected for the whole minute);
///   the alternative — waiting on a record the network cannot satisfy — is a permanent halt, which
///   the RC-4 drill measured as "the victim did not propose after restart".
fn spawn_own_record_reconciler(
    phase: crate::engine::node_phase::NodePhaseCell,
    dag: Arc<dyn BlockDagStorage>,
    retriever: Arc<BlockRetriever>,
    validator: rchain_models::validator::Validator,
    log: Arc<dyn Log>,
) {
    tokio::spawn(async move {
        let source = LogSource::new("casper.engine.NodeLaunch");
        // **The record is reconciled only after the node has caught up.** The catch-up walk is what
        // delivers the blocks this validator signed before it stopped; retiring on a timer that
        // starts at boot cut the walk off (measured: the recorded block arrived after the retire,
        // and the next proposal duplicated it locally). The phase is the signal: `Running` means
        // the walk has reached the window, so a block still absent then is genuinely absent from
        // what the peers serve.
        let wait_deadline = tokio::time::Instant::now() + Duration::from_secs(300);
        loop {
            if matches!(phase.phase(), crate::engine::node_phase::NodePhase::Running) {
                break;
            }
            if matches!(
                phase.phase(),
                crate::engine::node_phase::NodePhase::Blocked(_)
            ) {
                return;
            }
            if tokio::time::Instant::now() >= wait_deadline {
                log.warn(
                    source,
                    "own record: the node did not reach `Running` within five minutes; reconciling \
                     anyway",
                );
                break;
            }
            tokio::time::sleep(Duration::from_secs(1)).await;
        }
        let record = match dag.read_own_latest().await {
            Ok(record) => record,
            Err(error) => {
                log.error(
                    source,
                    &format!("the own-latest record could not be read at boot: {error}"),
                );
                return;
            }
        };
        let Some((height, seq, hash)) = record else {
            return;
        };
        let own_seen = {
            let repr = dag.get_representation().await;
            repr.dag_message_state
                .latest_msgs
                .get(&validator)
                .map(|message| message.sender_seq)
        };
        if own_seen.is_some_and(|seen| seq <= seen) {
            return;
        }
        for _ in 0..OWN_RECORD_ATTEMPTS {
            if dag.get_representation().await.dag_set.contains(&hash) {
                log.info(
                    source,
                    &format!(
                        "own record reconciled: the block signed at sequence {} (height {}) is in \
                         the DAG",
                        i64::from(seq),
                        i64::from(height)
                    ),
                );
                return;
            }
            retriever.request_missing_dependency(&hash).await;
            tokio::time::sleep(OWN_RECORD_TICK).await;
        }
        if dag.get_representation().await.dag_set.contains(&hash) {
            return;
        }
        match dag.clear_own_latest().await {
            Ok(()) => log.warn(
                source,
                &format!(
                    "own record retired: sequence {} (height {}, block {}) was asked of every \
                     answering peer for {} attempts and none serves it; the network dropped that \
                     branch, so the proposer derives from the round snapshot",
                    i64::from(seq),
                    i64::from(height),
                    hash.to_hex(),
                    OWN_RECORD_ATTEMPTS
                ),
            ),
            Err(error) => log.error(
                source,
                &format!(
                    "own record could not be retired ({error}); the proposer will keep waiting on \
                     sequence {}",
                    i64::from(seq)
                ),
            ),
        }
    });
}

/// Start the catch-up walk for a running phase, if that phase has an anchor and a peer to walk against.
///
/// **Called once per running phase, and that is new** (#320): the boot path starts it an extra time
/// because a reset has just put this node deliberately behind its peers, and the walk is what pulls it
/// back. The engine's door is swapped for the new walk's channel first, which drops the previous
/// sender — and *that* is how the walk that ended learns to stop (`run_catchup` breaks on a closed
/// channel), so the two walks cannot interleave.
#[allow(clippy::too_many_arguments)]
async fn start_catchup_if_anchored(
    phase_anchor: &mut Option<BlockHash>,
    block_range_door: &crate::engine::node_running::BlockRangeDoor,
    catchup: &Arc<CatchupWindow>,
    transport: &Arc<dyn TransportLayer>,
    rp_conf: &RPConf,
    connections: &ConnectionsCell,
    dag: &Arc<dyn BlockDagStorage>,
    resume: &Arc<dyn crate::engine::reset::SelfReplayResume>,
    log: &Arc<dyn Log>,
    source: LogSource,
) {
    let Some(anchor) = phase_anchor.take() else {
        return;
    };
    // **Only a node that named an anchor catches up.** An ordinary joiner is level with the fringe it
    // synced to; its first window would come back empty and the driver would release the gate having
    // done nothing, which is a round trip this avoids. If there is no bootstrap there is nobody to
    // walk against, so the driver is not started and the receive end is dropped with it.
    let Some(peer) = rp_conf.bootstrap.clone() else {
        log.warn(
            source,
            &format!(
                "an anchor ({}) was named without a bootstrap: nothing to catch up against",
                anchor.to_hex()
            ),
        );
        return;
    };
    start_walk(
        peer,
        block_range_door,
        catchup,
        transport,
        rp_conf,
        connections,
        dag,
        resume,
        log,
    )
    .await;
}

/// **Start one catch-up walk against `peer`.** The engine's door is swapped for the new walk's
/// channel first, which drops the previous sender — and *that* is how the walk that ended learns to
/// stop (`run_catchup` breaks on a closed channel), so two walks cannot interleave.
#[allow(clippy::too_many_arguments)]
async fn start_walk(
    peer: PeerNode,
    block_range_door: &crate::engine::node_running::BlockRangeDoor,
    catchup: &Arc<CatchupWindow>,
    transport: &Arc<dyn TransportLayer>,
    rp_conf: &RPConf,
    connections: &ConnectionsCell,
    dag: &Arc<dyn BlockDagStorage>,
    resume: &Arc<dyn crate::engine::reset::SelfReplayResume>,
    log: &Arc<dyn Log>,
) {
    let (block_range_tx, block_range_rx) = tokio::sync::mpsc::channel(4);
    *block_range_door.lock().await = block_range_tx;
    let (transport, conf, connections, dag, log, catchup, resume) = (
        transport.clone(),
        rp_conf.clone(),
        connections.clone(),
        dag.clone(),
        log.clone(),
        catchup.clone(),
        resume.clone(),
    );
    tokio::spawn(async move {
        catchup::run_catchup(
            transport,
            conf,
            connections,
            dag,
            log,
            catchup,
            resume,
            peer,
            block_range_rx,
        )
        .await;
    });
}

/// **The anchor's ancestor closure from DAG metadata** — the same walk the producer and joiner use.
/// **Which record anchors a boot?** (Law 108, review R2) A restart trusts the state on disk only
/// when a verified certificate says what that state is. Three cases, and none may be collapsed into
/// "run unanchored":
///
/// - the approved fringe is recorded and the certificate names exactly it — **re-verified**;
/// - both are recorded, they differ, and the accepted fringe is a **descendant extension** of the
///   certificate's anchor — the certificate still anchors the history; it is adopted as the base
///   and the window is re-derived (the in-place-restart case);
/// - both are recorded and the accepted fringe does **not** descend from the anchor — **mismatch**,
///   and the node must not adopt the certificate silently over an unrelated accepted fringe;
/// - no approved fringe is recorded at all — a genesis master, or an interrupted approved-fringe
///   write — the verified certificate is the only accepted-state record, so it is **adopted**.
///   Refusing to run here was the observed defect: a validator that had certified normally could
///   not restart at all.
#[derive(Debug, PartialEq, Eq)]
enum StoredFringeAgreement {
    Reverified,
    Mismatch { certified: usize, accepted: usize },
    Absent,
}

fn stored_fringe_agreement(
    recorded: Option<&BTreeSet<BlockHash>>,
    certified: &BTreeSet<BlockHash>,
) -> StoredFringeAgreement {
    match recorded {
        Some(accepted) if accepted == certified => StoredFringeAgreement::Reverified,
        Some(accepted) => StoredFringeAgreement::Mismatch {
            certified: certified.len(),
            accepted: accepted.len(),
        },
        None => StoredFringeAgreement::Absent,
    }
}

/// Where the boot certificate came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum BootCertificateSource {
    Stored,
    Fetched,
}

/// The certificate the reconnect branch runs from, and where it was found.
#[derive(Debug)]
struct BootCertificate {
    verified: crate::checkpoint::VerifiedCheckpoint,
    source: BootCertificateSource,
}

/// **The boot decision as a trace.** The coordinates a boot failure is read in: what the DAG holds,
/// what the store held, whether a source was configured, what it answered, and what was adopted.
/// The coordinate a refused boot is missing. The refusal prose names it in the trace; the enum is
/// what the Lean `BootCoordinate` and the evaluator's predicates range over.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum BootCoordinate {
    NoStoredCertificate,
    FetchFailed,
    VerifyFailed,
    ShardMismatch,
    StoreConflict,
    /// The certificate verified, but the accepted fringe is not anchored by it (the agreement
    /// stage, not the acquisition). A node that cannot attribute its accepted state refuses.
    FringeMismatch,
    /// A light join was attempted and the checkpoint sync stopped: the approved state could not be
    /// restored and the retries are spent. This is the join ladder's timeout rung, named so the
    /// decision trace says what the node did after the agreement refused it.
    SyncTerminal,
}

impl BootCoordinate {
    fn as_str(self) -> &'static str {
        match self {
            BootCoordinate::NoStoredCertificate => "no-stored-certificate",
            BootCoordinate::FetchFailed => "fetch-failed",
            BootCoordinate::VerifyFailed => "verify-failed",
            BootCoordinate::ShardMismatch => "shard-mismatch",
            BootCoordinate::StoreConflict => "store-conflict",
            BootCoordinate::FringeMismatch => "fringe-mismatch",
            BootCoordinate::SyncTerminal => "sync-terminal",
        }
    }
}

/// The boot decision's outcome type. `Genesis` and `Certified` are the two running outcomes;
/// `Refused` names the coordinate that was missing.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum BootOutcome {
    Genesis,
    Certified,
    Refused(BootCoordinate),
}

fn classify_boot_refusal(error: &str) -> BootCoordinate {
    if error.contains("no checkpoint certificate is stored and the checkpoint source refused") {
        BootCoordinate::FetchFailed
    } else if error.contains("failed re-verification")
        || error.contains("the fetched checkpoint certificate was refused")
    {
        BootCoordinate::VerifyFailed
    } else if error.contains("names shard") {
        BootCoordinate::ShardMismatch
    } else if error.contains("conflicts with") {
        BootCoordinate::StoreConflict
    } else {
        BootCoordinate::NoStoredCertificate
    }
}

fn boot_outcome(
    genesis_only: bool,
    acquisition: &Result<Option<BootCertificate>, String>,
) -> BootOutcome {
    match acquisition {
        Ok(Some(_)) => BootOutcome::Certified,
        Ok(None) if genesis_only => BootOutcome::Genesis,
        Ok(None) => BootOutcome::Refused(BootCoordinate::NoStoredCertificate),
        Err(error) => BootOutcome::Refused(classify_boot_refusal(error)),
    }
}

#[derive(Debug, serde::Serialize)]
struct BootTrace {
    kind: String,
    stage: String,
    dag_len: usize,
    genesis_only: bool,
    store_head: Option<String>,
    source_configured: bool,
    acquisition: String,
    served_digest: Option<String>,
    served_anchor: Option<String>,
    served_shard: Option<String>,
    shard_id: String,
    served_supporting_stake: Option<i128>,
    served_total_stake: Option<i128>,
    outcome: String,
    refusal_coordinate: Option<String>,
    accepted: bool,
    // **The agreement decision** (`stage: "decision"`). `accepted` on the acquisition trace means
    // "a verified certificate was acquired"; it does not mean the boot ran. A certificate can be
    // quorate and still not anchor the accepted fringe (a restart whose fence is *behind* the
    // certificate's anchor), and the node then refuses. Without these the trace says a refused
    // boot was safe — the model gap the RC-4 run at `e9508f5` exhibited.
    #[serde(skip_serializing_if = "Option::is_none")]
    fringe_agrees: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    anchor_closure_present: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    fringe_agreement: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    accepted_fringe: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    certified_fringe: Option<usize>,
    // **What the boot did after the agreement refused the local fringe** (join ladder, RC-4).
    // `"light-join"` means the node did not run from the accepted fringe at all; it ran from the
    // certified anchor the sync restored, and the stale fence was never served. The evaluator
    // reads this with `accepted` so a join is not mistaken for the refusal it replaced.
    #[serde(skip_serializing_if = "Option::is_none")]
    recovery: Option<String>,
}

/// Write the boot trace when `RNODE_TRACE_DIR` is set (the local claim harness sets it). A write
/// failure is not a consensus event and is ignored.
fn write_boot_trace(trace: &BootTrace) {
    crate::trace::write_trace("boot", trace);
}

/// **The decision trace's coordinates, kept from the acquisition until the outcome is known.**
///
/// A light join decides *before* the checkpoint sync has run; writing the decision there would
/// record an intention (`accepted: true`) for a boot that may still stop at the sync's terminal
/// signal. The coordinates are captured here and written once — after the sync produces an
/// accepted state, or after it names its terminal coordinate.
#[derive(Debug, Clone)]
struct BootDecision {
    dag_len: usize,
    genesis_only: bool,
    store_head: Option<String>,
    source_configured: bool,
    acquisition: String,
    served_digest: Option<String>,
    served_anchor: Option<String>,
    served_shard: Option<String>,
    shard_id: String,
    served_supporting_stake: Option<i128>,
    served_total_stake: Option<i128>,
    fringe_agreement: Option<String>,
    accepted_fringe: Option<usize>,
    certified_fringe: Option<usize>,
}

impl BootDecision {
    fn write(&self, accepted: bool, recovery: Option<&str>, refusal: Option<BootCoordinate>) {
        let fringe_agrees = !matches!(self.fringe_agreement.as_deref(), Some("mismatch"));
        write_boot_trace(&BootTrace {
            kind: "boot".to_string(),
            stage: "decision".to_string(),
            dag_len: self.dag_len,
            genesis_only: self.genesis_only,
            store_head: self.store_head.clone(),
            source_configured: self.source_configured,
            acquisition: self.acquisition.clone(),
            served_digest: self.served_digest.clone(),
            served_anchor: self.served_anchor.clone(),
            served_shard: self.served_shard.clone(),
            shard_id: self.shard_id.clone(),
            served_supporting_stake: self.served_supporting_stake,
            served_total_stake: self.served_total_stake,
            outcome: (if accepted {
                if self.genesis_only {
                    "genesis"
                } else {
                    "certified"
                }
            } else {
                "refused"
            })
            .to_string(),
            refusal_coordinate: refusal.map(|coordinate| coordinate.as_str().to_string()),
            accepted,
            fringe_agrees: Some(fringe_agrees),
            anchor_closure_present: Some(accepted),
            fringe_agreement: self.fringe_agreement.clone(),
            accepted_fringe: self.accepted_fringe,
            certified_fringe: self.certified_fringe,
            recovery: recovery.map(str::to_string),
        });
    }
}

/// **Acquire the boot certificate.** A stored head is re-verified; with none, the configured
/// checkpoint source is pulled, verified against the genesis bonds, shard-checked, recorded and
/// adopted. `Ok(None)` means there is no stored certificate *and* no source to ask — the caller
/// decides whether a genesis-only DAG can still proceed. A source that answers badly is a named
/// refusal, not a silent fall-through to the generic no-certificate sentence.
async fn acquire_boot_certificate(
    store: &rchain_block_storage::checkpoint_store::CheckpointStore,
    source: Option<&Arc<dyn crate::engine::checkpoint_source::CheckpointSource>>,
    bonds: &BTreeMap<rchain_models::validator::Validator, NonNegI64>,
    shard_id: &str,
    recorded_fringe: Option<&BTreeSet<BlockHash>>,
) -> Result<Option<BootCertificate>, String> {
    acquire_boot_certificate_with(
        store,
        source,
        bonds,
        shard_id,
        recorded_fringe,
        &|certificate, bonds| {
            crate::checkpoint::verify_genesis_rooted_certificate(certificate, bonds)
                .map_err(|e| e.to_string())
        },
    )
    .await
}

/// The acquisition with an injectable verifier, so the record/adopt mechanics are testable without
/// minting a quorum-signed certificate.
#[allow(clippy::too_many_arguments)]
async fn acquire_boot_certificate_with(
    store: &rchain_block_storage::checkpoint_store::CheckpointStore,
    source: Option<&Arc<dyn crate::engine::checkpoint_source::CheckpointSource>>,
    bonds: &BTreeMap<rchain_models::validator::Validator, NonNegI64>,
    shard_id: &str,
    recorded_fringe: Option<&BTreeSet<BlockHash>>,
    verify: &(dyn Fn(
        &rchain_models::casper::protocol::checkpoint::CheckpointCertificate,
        &BTreeMap<rchain_models::validator::Validator, NonNegI64>,
    ) -> Result<crate::checkpoint::VerifiedCheckpoint, String>
          + Send
          + Sync),
) -> Result<Option<BootCertificate>, String> {
    if let Some(certificate) = store.latest().await? {
        let verified = verify(&certificate, bonds).map_err(|e| {
            format!(
                "the stored checkpoint certificate failed re-verification at boot, so the \
                 accepted fringe cannot be attributed: {e}"
            )
        })?;
        if verified.checkpoint.shard_id != shard_id {
            return Err(format!(
                "the stored checkpoint certificate names shard {:?}, not this node's {:?}",
                verified.checkpoint.shard_id, shard_id
            ));
        }
        return Ok(Some(BootCertificate {
            verified,
            source: BootCertificateSource::Stored,
        }));
    }

    let Some(source) = source else {
        return Ok(None);
    };
    // **Ask for a certificate that anchors the accepted fringe before asking for the head.** A
    // restart that was down while the fence moved has a recorded fringe *behind* the served head;
    // the head cannot anchor it (its anchor is newer than every recorded member), and refusing on
    // that mismatch is the lagging-restart stall the RC-4 drill measured. The caller names anchors
    // from its own accepted fringe, so the source serves a stored certificate rather than choosing
    // the history. The head stays the fallback: a fresh joiner has no recorded fringe, and a peer
    // that predates the anchor route simply answers nothing here.
    let mut candidates: Vec<rchain_models::casper::protocol::checkpoint::CheckpointCertificate> =
        Vec::new();
    if let Some(fringe) = recorded_fringe {
        for anchor in fringe {
            if let Ok(certificate) = source.fetch_certificate_at_anchor(&anchor.to_hex()).await {
                candidates.push(certificate);
            }
        }
    }
    let mut head_error: Option<String> = None;
    match source.fetch_certificate().await {
        Ok(certificate) => candidates.push(certificate),
        Err(e) => head_error = Some(e),
    }
    if candidates.is_empty() {
        return Err(format!(
            "no checkpoint certificate is stored and the checkpoint source refused: {}",
            head_error.unwrap_or_else(|| "no certificate served".to_string())
        ));
    }

    let mut last_error: Option<String> = None;
    for certificate in candidates {
        let verified = match verify(&certificate, bonds) {
            Ok(verified) => verified,
            Err(e) => {
                last_error = Some(format!(
                    "the fetched checkpoint certificate was refused: {e}"
                ));
                continue;
            }
        };
        if verified.checkpoint.shard_id != shard_id {
            last_error = Some(format!(
                "the fetched checkpoint certificate names shard {:?}, not this node's {:?}",
                verified.checkpoint.shard_id, shard_id
            ));
            continue;
        }
        if let rchain_block_storage::checkpoint_store::Recorded::Conflict { existing_digest } =
            store.record(&verified.digest, &certificate).await?
        {
            return Err(format!(
                "the fetched checkpoint certificate conflicts with an already recorded statement \
                 at its anchor (existing {})",
                existing_digest.to_hex()
            ));
        }
        if let rchain_block_storage::checkpoint_store::Adoption::Conflict {
            head_digest,
            incoming_digest,
        } = store.adopt(&verified.digest, &certificate, false).await?
        {
            return Err(format!(
                "the fetched checkpoint certificate conflicts with the adopted head (head {:?}, \
                 incoming {})",
                head_digest.map(|digest| digest.to_hex()),
                incoming_digest.to_hex()
            ));
        }
        return Ok(Some(BootCertificate {
            verified,
            source: BootCertificateSource::Fetched,
        }));
    }
    Err(last_error.unwrap_or_else(|| "no checkpoint certificate could be verified".to_string()))
}

/// **Is every recorded fringe member the anchor or one of its descendants?** The DAG's message map
/// carries each block's `seen` set, so this is a lookup, not a walk. A member the DAG does not hold
/// is not evidence of descent and refuses the adoption (safe default).
async fn fringe_descends_from(
    dag: &dyn BlockDagStorage,
    recorded: &BTreeSet<BlockHash>,
    anchor: BlockHash,
) -> Result<bool, String> {
    let representation = dag.get_representation().await;
    let msg_map = &representation.dag_message_state.msg_map;
    for member in recorded {
        if *member == anchor {
            continue;
        }
        match msg_map.get(member) {
            Some(message) if message.seen.contains(&anchor) => {}
            _ => return Ok(false),
        }
    }
    Ok(true)
}

async fn anchor_closure(
    dag: &dyn BlockDagStorage,
    anchor: BlockHash,
) -> Result<Vec<rchain_models::casper::protocol::casper_message::BlockHeader>, String> {
    let mut seen = BTreeSet::new();
    let mut stack = vec![anchor];
    let mut headers = Vec::new();
    while let Some(hash) = stack.pop() {
        if !seen.insert(hash) {
            continue;
        }
        let metadata = dag.lookup(&hash).await?.ok_or_else(|| {
            format!(
                "the accepted anchor's ancestor {} has no DAG metadata, so the stored certificate \
                 cannot be re-verified",
                hash.to_hex()
            )
        })?;
        headers.push(metadata.to_header(false));
        stack.extend(metadata.justifications.iter().copied());
    }
    Ok(headers)
}

/// The boot rebuild, naming the missing input when the certificate was **fetched** and this node's
/// DAG does not hold its anchor closure. A stored certificate is the node's own history, so its
/// rebuild failure keeps the underlying reason.
async fn rebuild_window_for_boot(
    dag: &dyn BlockDagStorage,
    verified: &crate::checkpoint::VerifiedCheckpoint,
    fetched: bool,
) -> Result<BTreeSet<Blake2b256Hash>, String> {
    rebuild_window_from_dag(dag, verified)
        .await
        .map_err(|error| {
            if fetched {
                format!(
                "fetched-certificate-anchor-not-held: the fetched certificate's anchor is not in \
                 this node's DAG: {error}"
            )
            } else {
                error
            }
        })
}

/// **Rebuild and verify the certified validation window at boot** (review R2). The stored
/// certificate must carry both commitments; the DAG must hold the anchor's closure; the walked
/// headers must reproduce both commitments. A missing commitment, header or match refuses to run
/// with a named reason rather than substituting an empty window.
async fn rebuild_window_from_dag(
    dag: &dyn BlockDagStorage,
    verified: &crate::checkpoint::VerifiedCheckpoint,
) -> Result<BTreeSet<Blake2b256Hash>, String> {
    if verified.checkpoint.metadata_root.is_none() {
        return Err(
            "the stored certificate has no metadata commitment; this build refuses to run \
             without one"
                .to_string(),
        );
    }
    if verified.checkpoint.history_root.is_none() {
        return Err(
            "the stored certificate has no validation-window commitment; this build refuses to \
             run without one"
                .to_string(),
        );
    }
    let anchor = BlockHash::try_from_hex(&verified.checkpoint.anchor)
        .map_err(|e| format!("the stored certificate's anchor is not a block hash: {e}"))?;
    let closure = anchor_closure(dag, anchor).await?;
    crate::checkpoint::check_committed_headers(closure.iter())
        .map_err(|e| format!("the stored certificate's committed headers are inconsistent: {e}"))?;
    crate::checkpoint::verify_metadata_root(&verified.checkpoint, closure.iter()).map_err(|e| {
        format!("the stored certificate's metadata commitment does not verify: {e}")
    })?;
    // **The signed merge base is the anchor header's own fringe state** — the same check the
    // sync path makes. A v2 statement whose `fringeState` is not the anchor's committed
    // `fringe_state_hash` names a base its anchor does not, and this node will not run from it.
    if verified.checkpoint.fringe_state.is_some() {
        let anchor_header = closure
            .iter()
            .find(|header| header.block_hash == anchor)
            .ok_or_else(|| {
                "the stored certificate's committed header set does not hold its anchor".to_string()
            })?;
        let signed = crate::checkpoint::checkpoint_run_root(&verified.checkpoint)
            .map_err(|e| format!("the stored certificate's fringeState is malformed: {e}"))?;
        if signed.as_bytes() != anchor_header.fringe_state_hash.as_bytes() {
            return Err(format!(
                "the stored certificate's signed fringe state {} is not the anchor header's \
                 committed fringe state {}",
                signed.to_hex(),
                rchain_shared::base16::encode(anchor_header.fringe_state_hash.as_bytes())
            ));
        }
    }
    crate::checkpoint::verify_validation_window(&verified.checkpoint, closure.iter()).map_err(
        |e| format!("the stored certificate's validation-window commitment does not verify: {e}"),
    )?;
    Ok(
        rchain_models::casper::protocol::checkpoint::validation_window_roots(closure.iter())
            .into_iter()
            .map(|root| Blake2b256Hash::from_byte_array(&root))
            .collect(),
    )
}

/// **Seed the runtime window with the anchor's certified closure and its descendants.** A restart's
/// DAG holds post-anchor blocks whose children may arrive before this node produces a new block, and
/// the first post-checkpoint block may justify an ancestor below the anchor (a validator whose latest
/// message the proposer had not seen). Both are committed history, not a store guess. A block above
/// the anchor is seeded only when every justification is already seeded, so a fork that does not
/// descend from the anchor cannot enter the window.
async fn seed_derived_roots(
    dag: &dyn BlockDagStorage,
    anchor: &crate::engine::anchor::TrustAnchor,
    window: &mut crate::engine::anchor::AcceptedWindow,
) -> Result<(), String> {
    let anchor_height = match anchor {
        crate::engine::anchor::TrustAnchor::Genesis(_) => 0,
        crate::engine::anchor::TrustAnchor::Checkpoint { verified, .. } => {
            verified.checkpoint.anchor_height
        }
    };
    let anchor_block = anchor.block();
    let mut seeded = BTreeSet::new();
    if let crate::engine::anchor::TrustAnchor::Checkpoint { fringe, .. } = anchor {
        // The certificate's finalized fringe is committed at the anchor height. A post-checkpoint
        // block may justify one of these siblings even though it is not an ancestor of the anchor.
        seeded.extend(fringe.iter().copied());
    }

    // The anchor's ancestor closure: certified history the first post-anchor block may justify.
    let mut seen = BTreeSet::new();
    let mut stack = vec![anchor_block];
    while let Some(hash) = stack.pop() {
        if !seen.insert(hash) {
            continue;
        }
        let metadata = dag.lookup(&hash).await?.ok_or_else(|| {
            format!(
                "the accepted anchor's ancestor {} has no DAG metadata, so its roots cannot be \
                 seeded",
                hash.to_hex()
            )
        })?;
        window.note_roots(&metadata);
        seeded.insert(hash);
        stack.extend(metadata.justifications.iter().copied());
    }

    // The descendants above the anchor, in topological order. A block that is not rooted in the
    // seeded closure is not a descendant and is not admitted.
    let representation = dag.get_representation().await;
    let topo = representation
        .topo_sort_unsafe(anchor_height + 1, None)
        .map_err(|e| format!("the DAG above the accepted anchor is unreadable: {e}"))?;
    for hashes in topo {
        for hash in hashes {
            let Some(metadata) = dag.lookup(&hash).await? else {
                continue;
            };
            if !metadata.justifications.is_empty()
                && metadata.justifications.iter().all(|j| seeded.contains(j))
            {
                window.note_roots(&metadata);
                seeded.insert(hash);
            }
        }
    }
    Ok(())
}

