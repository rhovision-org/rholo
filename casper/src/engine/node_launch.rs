    /// **Law 84 / #456: the ceremony identity is the bonds file's first entry.** The keyed map the
    /// parser returns is sorted and would pick a different "first", so the file's order must win; a
    /// local key that is not the first bond refuses unless the autogen path's `.sk` supplies that
    /// bond's key.
    #[test]
    fn the_genesis_ceremony_is_the_first_bond_or_refused() {
        let dir = std::env::temp_dir().join(format!("n456-genesis-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let path = dir.join("bonds.txt");
        let first = ValidatorIdentity::from_private_key(PrivateKey::new(vec![1u8; 32]))
            .expect("the first identity");
        let second = ValidatorIdentity::from_private_key(PrivateKey::new(vec![2u8; 32]))
            .expect("the second identity");
        std::fs::write(
            &path,
            format!(
                "{} 10\n{} 10\n",
                base16::encode(first.public_key.bytes()),
                base16::encode(second.public_key.bytes())
            ),
        )
        .expect("bonds file");
        let path_str = path.to_str().expect("utf-8 temp path");

        let (bond, ceremony) =
            resolve_genesis_ceremony(path_str, &first).expect("the first bond may create");
        assert_eq!(bond, first.public_key);
        assert_eq!(ceremony.public_key, first.public_key);

        let err = resolve_genesis_ceremony(path_str, &second)
            .expect_err("the second bond must not create");
        assert!(err.contains("first bonded validator"), "{err}");
        assert!(
            err.contains(&base16::encode(first.public_key.bytes()))
                && err.contains(&base16::encode(second.public_key.bytes())),
            "the refusal must name both keys: {err}"
        );

        // The autogen path: the first bond's `.sk` is beside the file, so a standalone node can use
        // the generated identity instead of its own.
        std::fs::write(
            dir.join(format!("{}.sk", base16::encode(first.public_key.bytes()))),
            base16::encode(&[1u8; 32]),
        )
        .expect("the generated key file");
        let (bond, ceremony) =
            resolve_genesis_ceremony(path_str, &second).expect("the generated key may create");
        assert_eq!(bond, first.public_key);
        assert_eq!(
            ceremony.public_key, first.public_key,
            "the generated key's identity, not the local validator's"
        );

        std::fs::remove_dir_all(&dir).ok();
    }

    /// The wait ends as soon as a peer is there — the check is the first thing the loop does, so an
    /// already-connected node does not spend a poll interval idle before creating its genesis.
    #[tokio::test]
    async fn the_connection_wait_returns_immediately_when_a_peer_exists() {
        let conns = connections(vec![peer("p")]);
        tokio::time::timeout(
            Duration::from_secs(1),
            wait_for_first_connection(&conns, &NopLog),
        )
        .await
        .expect("a connected node must not wait");
    }

    /// With no peers the wait does **not** proceed: it polls, and the caller (`apply`) must not
    /// fall through to genesis creation or to running. The empty cell is never written to, so the
    /// future cannot complete — the timeout is the assertion, not a race.
    #[tokio::test]
    async fn the_connection_wait_blocks_while_there_are_no_peers() {
        let conns = connections(Vec::new());
        let result = tokio::time::timeout(
            // Comfortably beyond one poll interval, so the loop has had several chances to exit.
            Duration::from_millis(900),
            wait_for_first_connection(&conns, &NopLog),
        )
        .await;
        assert!(
            result.is_err(),
            "an unconnected node must keep waiting, not proceed"
        );
    }

    /// A peer arriving *after* the wait started releases it, which is the case the standalone
    /// detection depends on: the node is started, the wait begins, then the first peer connects.
    #[tokio::test]
    async fn the_connection_wait_is_released_by_a_late_peer() {
        let conns = connections(Vec::new());
        let writer = Arc::clone(&conns);
        tokio::spawn(async move {
            tokio::time::sleep(Duration::from_millis(300)).await;
            writer.write().await.push(peer("late"));
        });
        tokio::time::timeout(
            Duration::from_secs(5),
            wait_for_first_connection(&conns, &NopLog),
        )
        .await
        .expect("the late peer must release the wait");
    }

    struct FakeSource(
        Result<rchain_models::casper::protocol::checkpoint::CheckpointCertificate, String>,
    );

    #[async_trait::async_trait]
    impl crate::engine::checkpoint_source::CheckpointSource for FakeSource {
        async fn fetch_certificate(
            &self,
        ) -> Result<rchain_models::casper::protocol::checkpoint::CheckpointCertificate, String>
        {
            self.0.clone()
        }
    }

    /// A source that serves a certificate only for a named anchor, and refuses the head. The
    /// lagging-restart path asks for the anchor first; the head is the fallback.
    struct AnchorSource {
        anchor: String,
        certificate:
            Result<rchain_models::casper::protocol::checkpoint::CheckpointCertificate, String>,
    }

    #[async_trait::async_trait]
    impl crate::engine::checkpoint_source::CheckpointSource for AnchorSource {
        async fn fetch_certificate(
            &self,
        ) -> Result<rchain_models::casper::protocol::checkpoint::CheckpointCertificate, String>
        {
            Err("the head is unavailable".to_string())
        }

        async fn fetch_certificate_at_anchor(
            &self,
            anchor: &str,
        ) -> Result<rchain_models::casper::protocol::checkpoint::CheckpointCertificate, String>
        {
            if anchor.eq_ignore_ascii_case(&self.anchor) {
                self.certificate.clone()
            } else {
                Err(format!("no certificate for anchor {anchor}"))
            }
        }
    }

    fn a_certificate() -> rchain_models::casper::protocol::checkpoint::CheckpointCertificate {
        use rchain_models::casper::protocol::checkpoint::{Checkpoint, CheckpointCertificate};
        CheckpointCertificate {
            checkpoint: Checkpoint {
                shard_id: "root".to_string(),
                anchor: "11".repeat(32),
                anchor_height: 1,
                anchor_post_state: "22".repeat(32),
                fringe_state: None,
                fringe_hashes: vec!["11".repeat(32)],
                parent_digest: None,
                epoch: 0,
                metadata_root: None,
                history_root: None,
                fringe_headers_root: None,
            },
            attestations: Vec::new(),
        }
    }

