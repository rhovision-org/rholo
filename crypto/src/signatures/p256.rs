//! NIST P-256 (secp256r1) ECDSA verification.
//!
//! The counterpart of [`rho:crypto:p256Verify`](https://github.com/rhovision-org/rholo/issues/560).
//! WebCrypto (`crypto.subtle`, which browsers use for BYOID DID keys and passkeys) signs and
//! verifies ES256 with P-256 and SHA-256; the existing `secp256k1Verify` and `ed25519Verify`
//! contracts cannot check those signatures, so a Rholang contract had no way to verify a
//! browser-produced DID event on chain.
//!
//! **This is verification only.** P-256 is deliberately *not* added to [`super::signatures_alg`]:
//! that enum is the deploy-signature algorithm set, and a new member there would change what a
//! validator accepts as a deploy signature. The issue asks for a verifier, not a consensus
//! algorithm.
//!
//! ## Encodings (the decisions issue #560 left open)
//!
//! - **Message.** The caller passes the message, and this module hashes it with SHA-256 before
//!   verifying. That is what WebCrypto does: `subtle.sign({name: "ECDSA", hash: "SHA-256"}, key,
//!   data)` hashes `data` itself. Treating `data` as a 32-byte prehash (as `secp256k1Verify` does)
//!   would make every browser-produced signature fail. The hash is over the exact bytes given, so
//!   the caller is responsible for canonicalising the payload.
//! - **Signature.** Raw 64-byte `r || s`, which is what WebCrypto, JOSE/ES256 and COSE emit, and
//!   ASN.1 DER, which is what OpenSSL-style tooling emits and what `secp256k1Verify` takes. A
//!   64-byte input is tried as raw first (its natural reading) and then as DER, so both are
//!   accepted without a length-only guess.
//! - **Public key.** SEC1, compressed (33 bytes) or uncompressed (65 bytes). A JWK's `x` and `y`
//!   are the uncompressed body, so the bytes to pass are `0x04 || x || y`; the bare 64-byte
//!   `x || y` is not a SEC1 point and is refused.
//! - **High-S.** Accepted. ECDSA verification does not require a low-S signature, WebCrypto does
//!   not normalise S, and roughly half of all valid browser signatures have a high S. Rejecting
//!   them would turn a valid signature into `false` for no cryptographic gain. A caller that needs
//!   signature bytes to be a unique identifier (rather than a proof) must not use them as one:
//!   `(r, s)` and `(r, n - s)` are both valid.
//!
//! Verification is **total**: every malformed key, signature or length answers `false`, never an
//! error or a panic, because the bytes come from a caller and must not be able to fail loudly.

use crate::hash::sha256;
use p256::ecdsa::signature::hazmat::PrehashVerifier;
use p256::ecdsa::{Signature, VerifyingKey};

/// The NIST P-256 algorithm (verification only).
pub struct P256;

impl P256 {
    /// Verify an ECDSA/P-256 signature over the SHA-256 hash of `data`.
    ///
    /// `signature` is raw 64-byte `r || s` or ASN.1 DER; `pub_key` is a SEC1 compressed or
    /// uncompressed point. See the module documentation for why the message is hashed here and
    /// why high-S signatures are accepted.
    pub fn verify_bytes(data: &[u8], signature: &[u8], pub_key: &[u8]) -> bool {
        let Ok(verifying_key) = VerifyingKey::from_sec1_bytes(pub_key) else {
            return false;
        };
        let digest = sha256::hash(data);

        // WebCrypto/JOSE/COSE emit fixed-width `r || s`, and that is the reading a 64-byte input
        // gets first. If it parses but does not verify, fall through to DER: a DER signature can
        // also be 64 bytes, and "the raw reading of a DER signature" must not be the final word.
        if signature.len() == 64 {
            if let Ok(sig) = Signature::from_slice(signature) {
                if verifying_key.verify_prehash(&digest, &sig).is_ok() {
                    return true;
                }
            }
        }

        match Signature::from_der(signature) {
            Ok(sig) => verifying_key.verify_prehash(&digest, &sig).is_ok(),
            Err(_) => false,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use p256::elliptic_curve::sec1::ToSec1Point;
    use rchain_shared::base16;

    /// The message signed by both fixtures: a stand-in for a canonicalised BYOID create event.
    const MESSAGE: &[u8] = b"BYOID DID create event: {\"seq\":1,\"type\":\"create\"}";

    /// **Generated by WebCrypto, not by this crate.** Node 22:
    /// `subtle.generateKey({name:"ECDSA", namedCurve:"P-256"}, true, ["sign","verify"])` then
    /// `subtle.sign({name:"ECDSA", hash:"SHA-256"}, privateKey, MESSAGE)`. The raw signature is
    /// `r || s` and WebCrypto's own `subtle.verify` accepts it; it rejects the DER form below
    /// (`DataError`), which is why raw is the first reading.
    const WEBCRYPTO_PUBKEY: &str = "04e5afd086093b7e48b087683b8e1d3416d3dc8fc80c2a9fbf6080ed223602b49b9d0cc80f98afc9b1e738944a49517c322cce297f9c5c2072b7942143425684e3";
    const WEBCRYPTO_SIGNATURE: &str = "8e4492b9c343eac74a0b3c973e0e1a0f418256dcf1bad4f7481a6f66da500db38774f4c9159debb82a5f125107ca9e24beb7cdbd6042e9cbe13f2e208bc3a5e4";
    /// The same `(r, s)` as the raw signature, ASN.1 DER-encoded. It is the same proof, and this
    /// crate accepts it; WebCrypto does not.
    const WEBCRYPTO_SIGNATURE_DER: &str = "30460221008e4492b9c343eac74a0b3c973e0e1a0f418256dcf1bad4f7481a6f66da500db30221008774f4c9159debb82a5f125107ca9e24beb7cdbd6042e9cbe13f2e208bc3a5e4";

    /// A second WebCrypto key, used only to show that a valid signature under the wrong key is
    /// `false`.
    const OTHER_PUBKEY: &str = "04ca7c63bd3b7ee39f80202771a4444450b93f25f3716ad31ccf3b894e9f49981541788247ec3ca6793a9de193530016c0fde1743876a33acc2963ad8b34c1ac18";

    fn bytes(hex: &str) -> Vec<u8> {
        base16::unsafe_decode(hex)
    }

    /// The decision that makes browser signatures usable at all: the message is hashed with
    /// SHA-256 inside the verifier. If `data` were treated as a prehash, this 59-byte message
    /// would be reduced to its leftmost 32 bytes and never verify.
    #[test]
    fn a_webcrypto_raw_signature_verifies() {
        let pub_key = bytes(WEBCRYPTO_PUBKEY);
        let signature = bytes(WEBCRYPTO_SIGNATURE);

        assert!(
            P256::verify_bytes(MESSAGE, &signature, &pub_key),
            "the WebCrypto fixture must verify; it is the shape BYOID and passkeys produce"
        );
        assert_eq!(signature.len(), 64, "WebCrypto emits r || s");
    }

    /// Both SEC1 point encodings are accepted: compressed (33 bytes) and uncompressed (65 bytes).
    /// The compressed form is derived here from the uncompressed fixture, so the two are the same
    /// key and the only variable is the encoding.
    #[test]
    fn both_sec1_public_key_encodings_verify() {
        let pub_key = bytes(WEBCRYPTO_PUBKEY);
        let signature = bytes(WEBCRYPTO_SIGNATURE);
        let point = p256::PublicKey::from_sec1_bytes(&pub_key).expect("the fixture is a point");
        let compressed = point.to_sec1_point(true).as_bytes().to_vec();

        assert_eq!(compressed.len(), 33);
        assert!(P256::verify_bytes(MESSAGE, &signature, &compressed));
        assert!(P256::verify_bytes(MESSAGE, &signature, &pub_key));
    }

    /// DER is accepted as well as raw. The issue left the choice open; accepting both costs one
    /// parse and lets a contract use the encoding its signer already produces.
    #[test]
    fn a_der_encoded_signature_also_verifies() {
        let pub_key = bytes(WEBCRYPTO_PUBKEY);
        let der = bytes(WEBCRYPTO_SIGNATURE_DER);

        assert!(Signature::from_der(&der).is_ok(), "the fixture is DER");
        assert!(
            P256::verify_bytes(MESSAGE, &der, &pub_key),
            "DER is the same proof as the raw r || s fixture"
        );
        assert!(
            !P256::verify_bytes(MESSAGE, &der, &bytes(OTHER_PUBKEY)),
            "and the verdict still depends on the key"
        );
    }

    /// **High-S is accepted, deliberately.** ECDSA verification does not require low-S, and
    /// WebCrypto does not normalise. `(r, s)` and `(r, n - s)` are both valid signatures, so a
    /// verifier that rejected the second would answer `false` for a signature a browser just made.
    /// This test constructs the high-S twin of the fixture and pins that it still verifies.
    #[test]
    fn a_high_s_signature_is_accepted() {
        let pub_key = bytes(WEBCRYPTO_PUBKEY);
        let signature = bytes(WEBCRYPTO_SIGNATURE);
        let high_s = flip_s_to_the_high_half(&signature);

        assert_ne!(high_s, signature, "the twin must differ in s");
        assert!(
            P256::verify_bytes(MESSAGE, &high_s, &pub_key),
            "high-S is a valid ECDSA signature and WebCrypto produces it too"
        );
    }

    /// Verification is total, and the cases are the ones a contract can actually be handed:
    /// a different message, a different key, a tampered signature, truncated/oversized/empty
    /// signatures, and malformed keys (including the bare JWK `x || y`, which is not SEC1).
    #[test]
    fn malformed_inputs_and_wrong_keys_answer_false() {
        let pub_key = bytes(WEBCRYPTO_PUBKEY);
        let signature = bytes(WEBCRYPTO_SIGNATURE);

        // The control: the fixture verifies, so each `false` below is the arm under test.
        assert!(P256::verify_bytes(MESSAGE, &signature, &pub_key));

        // A different message, including a one-byte change, and the empty message.
        assert!(!P256::verify_bytes(
            b"BYOID DID create event: {\"seq\":2,\"type\":\"create\"}",
            &signature,
            &pub_key
        ));
        assert!(!P256::verify_bytes(b"", &signature, &pub_key));

        // A valid signature under a different key.
        assert!(!P256::verify_bytes(
            MESSAGE,
            &signature,
            &bytes(OTHER_PUBKEY)
        ));

        // A flipped bit in r, and a signature of the wrong length / the all-zero r,s.
        let mut tampered = signature.clone();
        tampered[0] ^= 0x01;
        assert!(!P256::verify_bytes(MESSAGE, &tampered, &pub_key));
        assert!(!P256::verify_bytes(MESSAGE, &signature[..63], &pub_key));
        assert!(!P256::verify_bytes(MESSAGE, &[1u8; 65], &pub_key));
        assert!(!P256::verify_bytes(MESSAGE, &[0u8; 64], &pub_key));
        assert!(!P256::verify_bytes(MESSAGE, &[], &pub_key));

        // Malformed keys: empty, a bare JWK x || y (64 bytes, no 0x04), a truncated point,
        // and a compressed point whose x is not on the curve.
        assert!(!P256::verify_bytes(MESSAGE, &signature, &[]));
        assert!(!P256::verify_bytes(MESSAGE, &signature, &pub_key[1..]));
        assert!(!P256::verify_bytes(MESSAGE, &signature, &pub_key[..64]));
        assert!(!P256::verify_bytes(MESSAGE, &signature, &[2u8; 33]));
    }

    /// `n - s`, big-endian, for the P-256 group order. Written out rather than pulled from the
    /// curve crate so the test states the value it is testing against.
    fn flip_s_to_the_high_half(signature: &[u8]) -> Vec<u8> {
        const ORDER: &str = "FFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551";
        let order: [u8; 32] = bytes(ORDER).try_into().expect("32-byte order");
        let s: [u8; 32] = signature[32..].try_into().expect("32-byte s");

        let mut high = [0u8; 32];
        let mut borrow = 0i16;
        for i in (0..32).rev() {
            let diff = order[i] as i16 - s[i] as i16 - borrow;
            if diff < 0 {
                high[i] = (diff + 256) as u8;
                borrow = 1;
            } else {
                high[i] = diff as u8;
                borrow = 0;
            }
        }

        [&signature[..32], &high].concat()
    }
}
